// A data type of the user exposes its own methods to a dynamic condition: `isUrgent()` (no parameter: `true` applies
// it, `false` its negation) and `atLeast(value)` (the value of the filter). A method it doesn't expose (`isLow`) is
// rejected; a class that exposes its methods without declaring them on its instance offers them only to a filter built
// at run time (from JSON); an absent value adds no condition; an alias of the class and a rule of version 1 that
// version 2 renamed still apply; and an exposed method that gives no condition is an error. Each filter emits the same
// SQL and params as the methods called directly.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { TsSqlError } from '../../../../../src/TsSqlError.js'
import { IntegersType, Table, exposeFilterOperations, filterOperation } from '../../../../../src/exports/v2/index.js'
import type { DynamicCondition, FilterOf } from '../../../../../src/exports/v2/index.js'
import type { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

// The priority of an issue: urgent from 3
abstract class PriorityType extends IntegersType<number, 'Priority'> {
    static override readonly type = 'Priority'
    // `urgent`, the name an older version of the class gave isUrgent
    static override readonly [filterOperation] = exposeFilterOperations(this, IntegersType, ['isUrgent', 'atLeast'], { urgent: 'isUrgent' })
    declare [filterOperation]: (typeof PriorityType)[typeof filterOperation]
    isUrgent() {
        return this.greaterOrEqual(3)
    }
    atLeast(value: number) {
        return this.greaterOrEqual(value)
    }
    // Not exposed
    isLow() {
        return this.lessOrEqual(1)
    }
}

// The same operations, exposed without declaring them on the instance
abstract class UndeclaredPriorityType extends IntegersType<number, 'UndeclaredPriority'> {
    static override readonly type = 'UndeclaredPriority'
    static override readonly [filterOperation] = exposeFilterOperations(this, IntegersType, ['isUrgent'])
    isUrgent() {
        return this.greaterOrEqual(3)
    }
}

const tIssuePriority = new class TIssuePriority extends Table<DBConnection, 'TIssuePriority'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    priority = this.column('priority', PriorityType)
    undeclaredPriority = this.column('priority', UndeclaredPriorityType)
    constructor() { super('issue') }
}()

type PriorityFilter = DynamicCondition<{ priority: PriorityType }>
type UndeclaredPriorityFilter = DynamicCondition<{ priority: UndeclaredPriorityType }>

function reasonOf(build: () => unknown): string {
    try {
        build()
    } catch (e) {
        return e instanceof TsSqlError ? e.errorReason.reason : `non-TsSqlError: ${String(e)}`
    }
    return '<no throw>'
}

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    async function idsWhere(filter: PriorityFilter, rows: Array<{ id: number }>) {
        ctx.mockNext(rows)
        return await ctx.conn.selectFrom(tIssuePriority)
            .where(ctx.conn.dynamicConditionFor({ priority: tIssuePriority.priority }).withValues(filter))
            .select({ id: tIssuePriority.id })
            .orderBy('id')
            .executeSelectMany()
    }

    test('data-type-operations/the-filter-of-a-data-type-has-the-operations-it-exposes', () => {
        assertType<Exact<FilterOf<PriorityType>['isUrgent'], boolean | undefined>>()
        assertType<Exact<FilterOf<PriorityType>['atLeast'], number | undefined>>()
        assertType<Exact<FilterOf<PriorityType>['lessThan'], number | undefined>>()
        assertType<Exact<'isLow' extends keyof FilterOf<PriorityType> ? true : false, false>>()
        assertType<Exact<'isUrgent' extends keyof FilterOf<UndeclaredPriorityType> ? true : false, false>>()
        // @ts-expect-error a method the data type doesn't expose
        const isLow: PriorityFilter = { priority: { isLow: true } }
        // @ts-expect-error a class that doesn't declare its operations on its instance doesn't offer them to the types
        const undeclared: UndeclaredPriorityFilter = { priority: { isUrgent: true } }
        expect([isLow, undeclared].length).toBe(2)
    })

    test('data-type-operations/an-operation-without-parameter-applies-with-true-and-negates-with-false', async () => {
        const urgent = await idsWhere({ priority: { isUrgent: true } }, [{ id: 3 }])
        const dynSql = ctx.lastSql
        const dynParams = ctx.lastParams
        expect(urgent).toEqual([{ id: 3 }])

        ctx.mockNext([])
        await ctx.conn.selectFrom(tIssuePriority)
            .where(tIssuePriority.priority.isUrgent())
            .select({ id: tIssuePriority.id })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toBe(dynSql)
        expect(ctx.lastParams).toEqual(dynParams)
        expect(dynSql).toMatchInlineSnapshot(`"select id as id from issue where priority >= ? order by id"`)
        expect(dynParams).toMatchInlineSnapshot(`
          [
            3,
          ]
        `)

        const notUrgent = await idsWhere({ priority: { isUrgent: false } }, [{ id: 1 }, { id: 2 }, { id: 4 }])
        expect(notUrgent).toEqual([{ id: 1 }, { id: 2 }, { id: 4 }])
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from issue where not (priority >= ?) order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            3,
          ]
        `)
    })

    test('data-type-operations/an-operation-with-a-parameter-takes-the-value-of-the-filter', async () => {
        const atLeastTwo = await idsWhere({ priority: { atLeast: 2 } }, [{ id: 1 }, { id: 3 }, { id: 4 }])
        const dynSql = ctx.lastSql
        const dynParams = ctx.lastParams
        expect(atLeastTwo).toEqual([{ id: 1 }, { id: 3 }, { id: 4 }])

        ctx.mockNext([])
        await ctx.conn.selectFrom(tIssuePriority)
            .where(tIssuePriority.priority.atLeast(2))
            .select({ id: tIssuePriority.id })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toBe(dynSql)
        expect(ctx.lastParams).toEqual(dynParams)
        expect(dynSql).toMatchInlineSnapshot(`"select id as id from issue where priority >= ? order by id"`)
        expect(dynParams).toMatchInlineSnapshot(`
          [
            2,
          ]
        `)
    })

    test('data-type-operations/a-filter-built-at-run-time-reaches-what-the-class-exposes', async () => {
        // A filter from JSON: the class of the column exposes isUrgent, though its instance doesn't declare it
        const fromJson: UndeclaredPriorityFilter = JSON.parse('{ "priority": { "isUrgent": true } }')
        ctx.mockNext([{ id: 3 }])
        const urgent = await ctx.conn.selectFrom(tIssuePriority)
            .where(ctx.conn.dynamicConditionFor({ priority: tIssuePriority.undeclaredPriority }).withValues(fromJson))
            .select({ id: tIssuePriority.id })
            .orderBy('id')
            .executeSelectMany()
        expect(urgent).toEqual([{ id: 3 }])
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from issue where priority >= ? order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            3,
          ]
        `)

        // A method the class doesn't expose is rejected, also from JSON
        const isLow: PriorityFilter = JSON.parse('{ "priority": { "isLow": true } }')
        expect(reasonOf(() => ctx.conn.dynamicConditionFor({ priority: tIssuePriority.priority }).withValues(isLow))).toBe('DYNAMIC_CONDITION_UNKNOWN_OPERATION')
    })

    test('data-type-operations/an-absent-value-adds-no-condition', async () => {
        // A filter from JSON, where a value it doesn't have is null
        const absent: PriorityFilter = JSON.parse('{ "priority": { "isUrgent": null, "atLeast": null } }')
        const all = await idsWhere(absent, [{ id: 1 }, { id: 2 }, { id: 3 }, { id: 4 }])
        expect(all).toEqual([{ id: 1 }, { id: 2 }, { id: 3 }, { id: 4 }])
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from issue order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
    })

    test('data-type-operations/a-rule-of-version-1-renamed-in-version-2-still-applies', async () => {
        // `smaller` is `lessThan` in version 2: the types don't offer it, a filter written for version 1 still has it
        const ofVersion1: PriorityFilter = JSON.parse('{ "priority": { "smaller": 2 } }')
        const smaller = await idsWhere(ofVersion1, [{ id: 2 }])
        expect(smaller).toEqual([{ id: 2 }])
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from issue where priority < ? order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2,
          ]
        `)
    })

    test('data-type-operations/an-alias-of-the-data-type-applies-the-method-it-stands-for', async () => {
        // @ts-expect-error the types offer only the names of the methods, not their aliases
        const typed: PriorityFilter = { priority: { urgent: true } }
        expect(typed).toEqual({ priority: { urgent: true } })
        // A filter of a system that still sends the old name
        const fromJson: PriorityFilter = JSON.parse('{ "priority": { "urgent": true } }')
        const urgent = await idsWhere(fromJson, [{ id: 3 }])
        expect(urgent).toEqual([{ id: 3 }])
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from issue where priority >= ? order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            3,
          ]
        `)
    })

    test('data-type-operations/an-exposed-operation-that-gives-no-condition-is-an-error', () => {
        // A method that gives a number, exposed past the types (as code without types or a method typed any would)
        expect(reasonOf(() => {
            abstract class TwicePriorityType extends IntegersType<number, 'TwicePriority'> {
                static override readonly type = 'TwicePriority'
                static override readonly [filterOperation] = exposeFilterOperations(this, IntegersType, ['twice'] as any)
                twice() {
                    return this.multiply(2)
                }
            }
            const tTwice = new class TTwice extends Table<DBConnection, 'TTwice'> {
                priority = this.column('priority', TwicePriorityType)
                constructor() { super('issue') }
            }()
            return ctx.conn.dynamicConditionFor({ priority: tTwice.priority }).withValues(JSON.parse('{ "priority": { "twice": 1 } }'))
        })).toBe('DYNAMIC_CONDITION_INVALID_OPERATION_RETURN_TYPE')
    })
})
