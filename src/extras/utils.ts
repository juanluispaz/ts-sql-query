import { isValueSource } from '../expressions/values.js'
import { isColumn, __getColumnPrivate } from '../utils/Column.js'
import { isColumnsGroupCandidate } from '../utils/columnPaths.js'
import type { AutogeneratedIdColumnKeys, ColumnKeys, ColumnsAtPaths, ExcludedColumns, IdColumnKeys, ProvidedIdColumnKeys, ShapeAtPaths, WithoutExcludedPaths, WritableColumnKeys } from './types.js'

// Only the columns are taken: the object can have anything else, and an object without columns is not a group
function extractTree(obj: any, prefix: string, ignore: any, accept: (value: any) => boolean, leaf: (value: any, path: string) => any, ancestors: object[]): any {
    const result: any = {}
    for (let key in obj) {
        const path = prefix + key
        if (path in ignore) {
            continue
        }
        const value = obj[key]
        if (accept(value)) {
            result[key] = leaf(value, path)
        } else if (isColumnsGroupCandidate(value) && !key.startsWith('__') && !ancestors.includes(value)) {
            ancestors.push(value)
            const group = extractTree(value, path + '.', ignore, accept, leaf, ancestors)
            ancestors.pop()
            if (Object.keys(group).length > 0) {
                result[key] = group
            }
        }
    }
    return result
}

function extractPaths(obj: any, prefix: string, ignore: any, accept: (value: any) => boolean, ancestors: object[], target: string[]): string[] {
    for (let key in obj) {
        const path = prefix + key
        if (path in ignore) {
            continue
        }
        const value = obj[key]
        if (accept(value)) {
            target.push(path)
        } else if (isColumnsGroupCandidate(value) && !key.startsWith('__') && !ancestors.includes(value)) {
            ancestors.push(value)
            extractPaths(value, path + '.', ignore, accept, ancestors, target)
            ancestors.pop()
        }
    }
    return target
}

function ignoreOf(exclude: readonly string[] | undefined): any {
    const ignore: any = Object.create(null)
    if (exclude) {
        for (let i = 0, length = exclude.length; i < length; i++) {
            ignore[exclude[i]!] = true
        }
    }
    return ignore
}

function isWritable(value: any): boolean {
    return isColumn(value) && __getColumnPrivate(value).__writable
}
function isId(value: any): boolean {
    return isColumn(value) && __getColumnPrivate(value).__writable && __getColumnPrivate(value).__isPrimaryKey
}
function isAutogeneratedId(value: any): boolean {
    return isColumn(value) && __getColumnPrivate(value).__writable && __getColumnPrivate(value).__isAutogeneratedPrimaryKey
}
function isProvidedId(value: any): boolean {
    return isColumn(value) && __getColumnPrivate(value).__writable && __getColumnPrivate(value).__isPrimaryKey && !__getColumnPrivate(value).__isAutogeneratedPrimaryKey
}
function theValue(value: any): any {
    return value
}
function thePath(_value: any, path: string): string {
    return path
}

export function extractColumnsFrom<O extends object, EXCLUDE extends ExcludedColumns<O> = never>(obj: O, exclude?: EXCLUDE[]): ColumnsAtPaths<O, WithoutExcludedPaths<ColumnKeys<O>, EXCLUDE>> {
    if (!obj) {
        return obj
    }
    return extractTree(obj, '', ignoreOf(exclude), isValueSource, theValue, [])
}

