// What OracleDBQueryRunner does with what the Oracle SqlBuilder records on the
// params: the category of the type of a RETURNING OUT bind (a temporal one is
// read back as a Date), the OUT binds of a PL/SQL block (one row per repeated name — how a
// multi-row INSERT returns its ids) and the affected-row count of a PL/SQL
// block, which Oracle doesn't report.

import oracledb from 'oracledb'
import { afterAll, beforeAll, describe, expect, test } from '../../lib/testRunner.js'
import type { QueryRunner } from '../../../src/queryRunners/QueryRunner.js'
import type { TypeCategory } from '../../../src/TypeAdapter.js'
import { OracleDBQueryRunner } from '../../../src/queryRunners/OracleDBQueryRunner.js'
import { setForcedAffectedRowCount } from '../../../src/utils/queryParamsMetadata.js'
import { isRealDbEnabled } from '../../lib/backends.js'
import { acquireRunnerTestDatabase } from '../../db/oracle/runners.js'

describe.skipIf(!isRealDbEnabled('oracle', 'docker', 'newest', 'oracledb'))('OracleDBQueryRunner: out binds', () => {
    let db: Awaited<ReturnType<typeof acquireRunnerTestDatabase>> | undefined
    let connection: oracledb.Connection | undefined
    let runner: QueryRunner | undefined
    const r = () => runner!

    beforeAll(async () => {
        db = await acquireRunnerTestDatabase()
        connection = await oracledb.getConnection({ user: db.user, password: db.password, connectString: db.connectString })
        runner = new OracleDBQueryRunner(connection)
        await r().executeDatabaseSchemaModification("begin execute immediate 'drop table rt_moment'; exception when others then if sqlcode != -942 then raise; end if; end;")
        await r().executeDatabaseSchemaModification('create table rt_moment (id number(10) generated by default as identity primary key, d date, ts timestamp)')
    }, 300_000)
    afterAll(async () => {
        await connection?.close()
        await db?.release()
    }, 300_000)

    function insertReturningMoments(types: [TypeCategory, TypeCategory]): { sql: string, params: any[] } {
        const params: any[] = []
        const d = r().addParam(params, new Date(Date.UTC(2026, 9, 25)), 'localDateTime', 'localDateTime')
        const ts = r().addParam(params, new Date(Date.UTC(2026, 9, 25, 10, 30, 15)), 'localDateTime', 'localDateTime')
        const dOut = r().addOutParam(params, 'd', types[0], types[0])
        const tsOut = r().addOutParam(params, 'ts', types[1], types[1])
        return { sql: `insert into rt_moment (d, ts) values (${d}, ${ts}) returning d, ts into ${dOut}, ${tsOut}`, params }
    }

    test('temporal-out-binds-with-their-data-type-are-dates', async () => {
        for (const types of [['localDate', 'localDateTime'], ['customLocalDate', 'customLocalDateTime'], ['localDate', 'localTime'], ['customLocalDate', 'customLocalTime']] as const) {
            const { sql, params } = insertReturningMoments([types[0], types[1]])
            const row = await r().executeInsertReturningOneRow(sql, params)
            expect(row.d).toBeInstanceOf(Date)
            expect(row.ts).toBeInstanceOf(Date)
        }
    })

    test('out-binds-without-a-temporal-data-type-are-strings', async () => {
        const { sql, params } = insertReturningMoments(['string', ''])
        const row = await r().executeInsertReturningOneRow(sql, params)
        expect(typeof row.d).toBe('string')
        expect(typeof row.ts).toBe('string')
    })

    test('out-binds-of-a-pl-sql-block-make-one-row-per-repeated-name', async () => {
        const params: any[] = []
        const sql = `begin insert into rt_moment (d) values (${r().addParam(params, new Date(), 'localDateTime', 'localDateTime')}) returning id into ${r().addOutParam(params, '', 'int', 'int')};`
            + ` insert into rt_moment (d) values (${r().addParam(params, new Date(), 'localDateTime', 'localDateTime')}) returning id into ${r().addOutParam(params, '', 'int', 'int')}; end;`
        const ids = (await r().executeInsertReturningMultipleLastInsertedId(sql, params)).map(Number)
        expect(ids).toHaveLength(2)
        expect(ids[1]!).toBeGreaterThan(ids[0]!)
    })

    test('a-pl-sql-block-reports-the-affected-rows-the-builder-recorded', async () => {
        const params: any[] = []
        setForcedAffectedRowCount(params, 2)
        const inserted = await r().executeInsert('begin insert into rt_moment (d) values (sysdate); insert into rt_moment (d) values (sysdate); end;', params)
        expect(inserted).toBe(2)
    })

    test('a-mutation-returning-nothing-into-out-binds', async () => {
        const params: any[] = []
        const sql = `update rt_moment set d = d where id < 0 returning id into ${r().addOutParam(params, 'id', 'int', 'int')}`
        expect(await r().executeUpdateReturningManyRows(sql, params)).toEqual([])
    })
})
