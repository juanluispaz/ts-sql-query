-- Int caller-provided PK carrying a scaling TypeAdapter (invoice_no stored x10).
CREATE TABLE invoice (
    invoice_no NUMBER PRIMARY KEY,
    total NUMBER NOT NULL
);

-- Every column factory carries its trailing-TypeAdapter overload.
-- entry_no autogenerated (plusOffsetAdapter, read +1000); amount/memo carry
-- scaledTenthAdapter (stored x10, read /10) over a DB DEFAULT; tag is virtual
-- (no DB column).
CREATE TABLE ledger_entry (
    entry_no NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    amount NUMBER DEFAULT 100 NOT NULL,
    memo NUMBER DEFAULT 50,
    discount NUMBER
);

CREATE TABLE project_release (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    project_id NUMBER NOT NULL,
    version VARCHAR2(32) NOT NULL,
    channel VARCHAR2(16) NOT NULL,
    signing_key RAW(16),
    released_on DATE NOT NULL,
    cutoff_time TIMESTAMP NOT NULL,
    signed_off_at TIMESTAMP,
    -- REQUIRED customLocalDateTime twin of signed_off_at.
    published_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    is_signed NUMBER(1),
    download_count NUMBER(19),
    avg_rating BINARY_DOUBLE,
    notes VARCHAR2(255) GENERATED ALWAYS AS ('release-' || version) VIRTUAL,
    CONSTRAINT fk_release_project FOREIGN KEY (project_id) REFERENCES project(id),
    CONSTRAINT uk_release_version UNIQUE (project_id, version)
);

-- Project review fixture: non-boolean per-column TypeAdapter on score (int,
-- stored x10) + reviewer_code (string, bracketed), an OPTIONAL localDate
-- (review_date) and a REQUIRED localTime (review_time).
CREATE TABLE project_review (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    project_id NUMBER NOT NULL,
    reviewer_code VARCHAR2(32) NOT NULL,
    score NUMBER NOT NULL,
    review_date DATE,
    review_time TIMESTAMP NOT NULL,
    CONSTRAINT fk_review_project FOREIGN KEY (project_id) REFERENCES project(id)
);


