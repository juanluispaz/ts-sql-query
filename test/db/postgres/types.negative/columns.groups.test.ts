// What a table with groups of columns doesn't accept when it's written.

import { expect, test } from '../../../lib/testRunner.js'
import type { InsertableRow, UpdatableRow } from '../../../../src/extras/types.js'
import { extractColumnNamesFrom, extractColumnsFrom } from '../../../../src/extras/utils.js'
import { Table } from '../../../../src/Table.js'
import { Values } from '../../../../src/Values.js'
import { type DBConnection } from '../domain/connection.js'

class TIssueGrouped extends Table<DBConnection, 'TIssueGrouped'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    location = {
        projectId: this.column('project_id', 'int'),
        number: this.column('number', 'int'),
    }
    title = this.column('title', 'string')
    tracking = {
        assigneeId: this.optionalColumn('assignee_id', 'int'),
    }
    settings = { label: 'not a column' }
    constructor() { super('issue') }
}
const tGrouped = new TIssueGrouped()

class TOptionalGroup extends Table<DBConnection, 'TOptionalGroup'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    title = this.column('title', 'string')
    assignment = {
        assigneeId: this.optionalColumn('assignee_id', 'int').asRequiredInOptionalObject(),
        parentId: this.optionalColumn('parent_id', 'int'),
    }
    constructor() { super('issue') }
}
const tOptionalGroup = new TOptionalGroup()

class ValuesGrouped extends Values<DBConnection, 'valuesGrouped'> {
    id = this.column('int')
    location = { projectId: this.column('int') }
}

declare const conn: DBConnection

// `conn` is type-only: the function below is checked by tsc but never invoked.
function _typeNegatives() {
    // A required group must be provided
    {
        // @ts-expect-error location is required
        const row: InsertableRow<TIssueGrouped> = { title: 'a' }
        // @ts-expect-error location is required
        conn.insertInto(tGrouped).set({ title: 'a' }).executeInsert()
        void row
    }

    // A required column of a group must be provided
    {
        // @ts-expect-error number is required in the group
        const row: InsertableRow<TIssueGrouped> = { title: 'a', location: { projectId: 1 } }
        // @ts-expect-error number is required in the group
        conn.insertInto(tGrouped).set({ title: 'a', location: { projectId: 1 } })
        void row
    }

    // A group only has its columns
    {
        // @ts-expect-error other is not a column of the group
        const row: InsertableRow<TIssueGrouped> = { title: 'a', location: { projectId: 1, number: 1, other: 1 } }
        // @ts-expect-error other is not a column of the group
        const updatable: UpdatableRow<TIssueGrouped> = { location: { other: 1 } }
        void row
        void updatable
    }

    // What is not a column cannot be written
    {
        // @ts-expect-error settings has no columns
        conn.update(tGrouped).set({ settings: { label: 'a' } })
        // @ts-expect-error settings has no columns
        conn.update(tGrouped).dynamicSet().ignoreIfSet('settings')
        // @ts-expect-error settings has no columns
        conn.update(tGrouped).dynamicSet().ignoreIfSet('settings.label')
        // @ts-expect-error nothing is a column of the group with this name
        conn.update(tGrouped).dynamicSet().ignoreIfSet('location.other')
    }

    // A group with a required column cannot be null
    {
        // @ts-expect-error location has required columns
        conn.update(tGrouped).set({ location: null })
    }

    // A group left without value keeps the insert from being executed
    {
        // @ts-expect-error location.number is required and it's not kept, the group is missing
        conn.insertInto(tGrouped).dynamicSet().set({ title: 'a', location: { projectId: 1, number: 1 } }).keepOnly('title', 'location.projectId').executeInsert()
        // @ts-expect-error the group is missing
        conn.insertInto(tGrouped).dynamicSet().set({ title: 'a' }).executeInsert()
        // @ts-expect-error a required column of the group was ignored, the group is missing
        conn.insertInto(tGrouped).dynamicSet().set({ title: 'a', location: { projectId: 1, number: 1 } }).ignoreIfSet('location.number').executeInsert()
    }

    // Required in the optional object means required when the group is provided
    {
        // @ts-expect-error assigneeId is required when the group is provided
        const row: InsertableRow<TOptionalGroup> = { title: 'a', assignment: { parentId: 1 } }
        // @ts-expect-error assigneeId is required when the group is provided
        conn.insertInto(tOptionalGroup).set({ title: 'a', assignment: { parentId: 1 } })
        void row
    }

    // A shape must cover the required columns of the group
    {
        // @ts-expect-error location.number has no value in the shape
        conn.insertInto(tGrouped).shapedAs({ project: 'location.projectId', title: 'title' }).set({ project: 1, title: 'a' }).executeInsert()
    }

    // A shape names columns, not groups
    {
        // @ts-expect-error location is a group
        conn.update(tGrouped).shapedAs({ place: 'location' })
        // @ts-expect-error the group has no such column
        conn.update(tGrouped).shapedAs({ place: 'location.other' })
    }

    // The rows of values have the groups
    {
        // @ts-expect-error location is required
        Values.create(ValuesGrouped, 'valuesGrouped', [{ id: 1 }])
        // @ts-expect-error projectId is required in the group
        Values.create(ValuesGrouped, 'valuesGrouped', [{ id: 1, location: {} }])
    }

    // Extract only leaves out what exists
    {
        // @ts-expect-error settings has no columns
        extractColumnsFrom(tGrouped, ['settings'])
        // @ts-expect-error the group has no such column
        extractColumnNamesFrom(tGrouped, ['location.other'])
    }
}

test('columns-groups-negative-types', () => {
    expect(typeof _typeNegatives).toBe('function')
})
