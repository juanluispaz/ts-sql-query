// identifier on at least one of them. The positions: a table name in from, join, insert into, update and delete; a table
// alias; a column, bare or qualified (also `inserted.` / `deleted.` of output); a column alias (also in output, for json
// path and the column list of values); order by and group by; `next value for` of a sequence; the name of a with (also
