// Ids encrypted by the connection: a `customComparable` type 'encryptedID' whose
// `transformValueToDB` decrypts the text with `IDEncrypter` and sends the number as
// a bigint, and whose `transformValueFromDB` reads the number as a bigint and hands
// back its encrypted text. The tables below are the domain's organization, project
// and issue tables with their ids declared with that type.
//
// The tests cover the paths where more than one id comes back (several inserted
// rows, an insert from a select, the returning of an insert, an update and a
// delete), a range comparison (the database compares the decrypted numbers), and
// ids that travel inside JSON (an aggregated array, an inline aggregated array and
// a recursive select), where each id arrives as a JSON number and is converted to
// a bigint before it is encrypted.

