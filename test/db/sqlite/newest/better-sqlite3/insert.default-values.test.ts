// Behavioral coverage of `connection.insertInto(t).defaultValues()`,
// which triggers `_buildInsertDefaultValues` in each SqlBuilder. Each
// dialect emits its own form, pinned per cell by the snapshot below.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection, tLedgerEntry } from '../../domain/connection.js'
import { ctx } from './setup.js'

// Local-only table whose only column is an autogenerated PK, so
// `RequiredColumnsForSetOf` resolves to `never` here and `.defaultValues()`
// types correctly with no cast needed.
class TDefaultsOnly extends Table<DBConnection, 'TDefaultsOnly'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    constructor() { super('defaults_only_table_only_for_sql_test') }
}
const tDefaultsOnly = new TDefaultsOnly()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('insert default values', async () => {
        ctx.mockNext(99)
        let id: number | undefined
        let thrownError: unknown
        try {
            id = await ctx.conn.insertInto(tDefaultsOnly)
                .defaultValues()
                .returningLastInsertedId()
                .executeInsert()
        } catch (e) {
            // The table is absent from the schema, so the real INSERT fails
            // referencing the missing relation.
            thrownError = e
        }
        expect(ctx.lastSql).toMatchInlineSnapshot(`"insert into defaults_only_table_only_for_sql_test default values returning id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        if (ctx.realDbEnabled) {
            expect((thrownError as Error).message).toMatch(/no such table|defaults_only_table_only_for_sql_test/)
        } else {
            expect(id).toBe(99)
        }
    })

    // The two tests below use the REAL, seeded `tLedgerEntry` table (every one
    // of its columns is defaulted, so `.defaultValues()` typechecks with no
    // cast). This lets the `default values ... returning` path run end-to-end.
    // They return `amount`, which carries a CONSTANT column default (100, read
    // as 10 by its `/10` value-transform adapter), so the returned value is
    // deterministic in both mock and real modes — one assertion holds for both.
    // Each insert is wrapped in a rollback so the real row does not persist.

    test('default values returning an object', async () => {
        // `insert into <t> default values returning <cols>` — the object-projection
        // returning path on a DEFAULT VALUES insert (distinct from the
        // returningLastInsertedId path above).
        ctx.mockNext([{ amount: 100 }])
        await ctx.withRollback(async () => {
            const rows = await ctx.conn.insertInto(tLedgerEntry)
                .defaultValues()
                .returning({ amount: tLedgerEntry.amount })
                .executeInsertMany()
            expect(ctx.lastSql).toMatchInlineSnapshot(`"insert into ledger_entry default values returning amount as amount"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
            assertType<Exact<typeof rows, Array<{ amount: number }>>>()
            expect(rows).toEqual([{ amount: 10 }])
        })
    })

    test('default values returning one column', async () => {
        // `insert into <t> default values returning <col>` — the single-column
        // returning path on a DEFAULT VALUES insert; the result is a bare array of
        // the column's type.
        ctx.mockNext([100])
        await ctx.withRollback(async () => {
            const rows = await ctx.conn.insertInto(tLedgerEntry)
                .defaultValues()
                .returningOneColumn(tLedgerEntry.amount)
                .executeInsertMany()
            expect(ctx.lastSql).toMatchInlineSnapshot(`"insert into ledger_entry default values returning amount as result"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
            assertType<Exact<typeof rows, number[]>>()
            expect(rows).toEqual([10])
        })
    })
})
