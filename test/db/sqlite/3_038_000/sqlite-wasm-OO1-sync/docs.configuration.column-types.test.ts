// The page stores the color in a binary column; organization.plan holds it here as a hex string, which keeps the
// round trip through the connection on every database.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'
import { sync } from '../../../../../src/extras/sync.js'
import type { TypeCategory } from '../../../../../src/TypeAdapter.js'

interface RgbColor { r: number, g: number, b: number }

function isRgbColor(value: object): value is RgbColor {
    return 'r' in value && 'g' in value && 'b' in value
}

function toHexPair(value: number): string {
    return value.toString(16).padStart(2, '0')
}

class RgbColorConnection extends DBConnection {
    protected override transformValueFromDB(value: unknown, type: string, typeCategory: TypeCategory) {
        if (type === 'RgbColor' && value) {
            if (typeof value === 'string' && value.length === 7) {
                return { r: parseInt(value.slice(1, 3), 16), g: parseInt(value.slice(3, 5), 16), b: parseInt(value.slice(5, 7), 16) }
            }
            throw new Error(`Cannot decode database value ${String(value)} (type ${typeof value}) as RgbColor`)
        }
        return super.transformValueFromDB(value, type, typeCategory)
    }
    protected override transformValueToDB(value: unknown, type: string, typeCategory: TypeCategory) {
        if (type === 'RgbColor' && value) {
            if (typeof value === 'object' && isRgbColor(value)) {
                return `#${toHexPair(value.r)}${toHexPair(value.g)}${toHexPair(value.b)}`
            }
            throw new Error(`Cannot encode value ${String(value)} for database`)
        }
        return super.transformValueToDB(value, type, typeCategory)
    }
    protected override transformPlaceholder(placeholder: string, type: string, typeCategory: TypeCategory, valueSentToDB: unknown): string {
        if (type === 'RgbColor') {
            return 'cast(' + placeholder + ' as text)'
        }
        return super.transformPlaceholder(placeholder, type, typeCategory, valueSentToDB)
    }
}

const tOrganizationColor = new class TOrganizationColor extends Table<DBConnection, 'TOrganizationColor'> {
    id    = this.autogeneratedPrimaryKey('id', 'int')
    color = this.column<RgbColor, 'RgbColor'>('plan', 'custom', 'RgbColor')
    constructor() { super('organization') }
}()

type ExactDecimal = string & { readonly __brand: 'ExactDecimal' }

class ExactDecimalConnection extends DBConnection {
    protected override transformValueFromDB(value: unknown, type: string, typeCategory: TypeCategory) {
        if (type === 'ExactDecimal' && value !== null && value !== undefined) {
            return String(value)
        }
        return super.transformValueFromDB(value, type, typeCategory)
    }
    protected override transformValueToDB(value: unknown, type: string, typeCategory: TypeCategory) {
        if (type === 'ExactDecimal') {
            return value
        }
        return super.transformValueToDB(value, type, typeCategory)
    }
}

type Units = number & { readonly __brand: 'Units' }

const tExactAmount = new class TExactAmount extends Table<DBConnection, 'TExactAmount'> {
    id = this.primaryKey('id', 'int')
    amount = this.optionalColumn<string, 'Amount'>('amount', 'customDecimal', 'Amount')
    price = this.optionalColumn<string, 'Amount'>('price', 'customDecimal', 'Amount')
    constructor() {
        super('exact_amount')
    }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:column-types/global-type-adapter-placeholder', async () => {
        const color: RgbColor = { r: 1, g: 2, b: 255 }
        ctx.mockNext(1)
        ctx.mockNext({ id: 1, color: '#0102ff' })
        const connection = ctx.withConnection(RgbColorConnection)

        await ctx.withRollback(async () => {
            // doc-start
            const updatedRows = sync(connection.update(tOrganizationColor)
                .set({ color })
                .where(tOrganizationColor.id.equals(1))
                .executeUpdate())
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update organization set "plan" = cast(?1 as text) where id = ?2"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "#0102ff",
                1,
              ]
            `)
            assertType<Exact<typeof updatedRows, number>>()
            expect(updatedRows).toBe(1)

            const organization = sync(connection.selectFrom(tOrganizationColor)
                .where(tOrganizationColor.id.equals(1))
                .select({ id: tOrganizationColor.id, color: tOrganizationColor.color })
                .executeSelectOne())

            assertType<Exact<typeof organization, { id: number; color: RgbColor }>>()
            expect(organization).toEqual({ id: 1, color })
        })
    })

    test('docs:column-types/custom-type-converted-as-its-category', async () => {
        // The SQL gives both values as text: the customInt is converted as an int, the custom arrives as it comes
        ctx.mockNext({ units: '42', tag: '42' })
        const row = sync(ctx.conn.selectFromNoTable()
            .select({
                units: ctx.conn.fragmentWithType<Units, 'Units'>('customInt', 'Units', 'required').sql`'42'`,
                tag: ctx.conn.fragmentWithType<string, 'Tag'>('custom', 'Tag', 'required').sql`'42'`,
            })
            .executeSelectOne())
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select '42' as units, '42' as tag"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof row, { units: Units; tag: string }>>()
        expect(row).toEqual({ units: 42, tag: '42' })
    })

    test('docs:column-types/exact-decimal-kept-as-text', async () => {
        const amount = '12345678901234567890.123456789' as ExactDecimal
        ctx.mockNext('12345678901234567890.123456789')
        const connection = ctx.withConnection(ExactDecimalConnection)
        // doc-start
        const result = sync(connection.selectFromNoTable()
            .selectOneColumn(connection.const<ExactDecimal, 'ExactDecimal'>(amount, 'customDouble', 'ExactDecimal'))
            .executeSelectOne())
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select ?1 as result"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "12345678901234567890.123456789",
          ]
        `)
        assertType<Exact<typeof result, ExactDecimal>>()
        expect(result).toBe('12345678901234567890.123456789')
    })

    test('docs:column-types/exact-decimals', async () => {
        ctx.mockNext([
            { id: 1, amount: '12345678901234567890.1234567891', next: '12345678901234567890.1234567892' },
            { id: 5, amount: '98765432109876543210.987654321', next: '98765432109876543210.9876543211' },
        ])
        const connection = ctx.conn
        // doc-start
        const rows = sync(connection.selectFrom(tExactAmount)
            .where(tExactAmount.price.greaterThan('1'))
            .select({
                id: tExactAmount.id,
                amount: tExactAmount.amount,
                next: tExactAmount.amount.add('0.0000000001'),
            })
            .orderBy('id')
            .executeSelectMany())
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, amount as amount, (select case when typeof(tsq_v) <> 'text' then tsq_v when instr(tsq_v, '.') = 0 then (case when tsq_v = '-0' then '0' else tsq_v end) when rtrim(rtrim(tsq_v, '0'), '.') in ('-0', '-', '') then '0' else rtrim(rtrim(tsq_v, '0'), '.') end from (select case when amount is null then null else decimal_add(amount, ?1) end as tsq_v)) as next from exact_amount where decimal_cmp(price, ?2) > 0 order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "0.0000000001",
            "1",
          ]
        `)
        assertType<Exact<typeof rows, { id: number; amount?: string; next?: string }[]>>()
        expect(rows).toEqual([
            { id: 1, amount: '12345678901234567890.1234567891', next: '12345678901234567890.1234567892' },
            { id: 5, amount: '98765432109876543210.987654321', next: '98765432109876543210.9876543211' },
        ])
    })
})
