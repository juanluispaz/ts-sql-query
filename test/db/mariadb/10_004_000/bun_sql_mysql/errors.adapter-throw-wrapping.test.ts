// The error the adapters throw, and the raw values they were handed.
const adapterFailure = new Error('adapter rejected the value')
let seenByAdapter: Array<string | number> = []

const rejectingAdapter: TypeAdapter = {
    transformValueFromDB(value) {
        if (typeof value === 'string' || typeof value === 'number') seenByAdapter.push(value)
        throw adapterFailure
    },
    transformValueToDB(value, type, next) {
        return next.transformValueToDB(value, type)
    },
}

// `issue` with a title the application refuses to read.
const tIssueRejectingTitle = new class TIssueRejectingTitle extends Table<DBConnection, 'TIssueRejectingTitle'> {
    id        = this.autogeneratedPrimaryKey('id', 'int')
    projectId = this.column('project_id', 'int')
    number    = this.column('number', 'int')
    title     = this.column('title', 'string', rejectingAdapter)
    status    = this.column('status', 'string')
    priority  = this.column('priority', 'int')
    constructor() { super('issue') }
}()

// `ledger_entry` whose generated entry number the application refuses to read.
const tLedgerEntryRejectingEntryNo = new class TLedgerEntryRejectingEntryNo extends Table<DBConnection, 'TLedgerEntryRejectingEntryNo'> {
    entryNo = this.autogeneratedPrimaryKey('entry_no', 'int', rejectingAdapter)
    amount  = this.columnWithDefaultValue('amount', 'int')
    constructor() { super('ledger_entry') }
}()

// A connection exposing `cm_str()` (returns 'hello') read through the rejecting adapter.
class RejectingFunctionConnection extends DBConnection {
    callCmStrRejected(): Promise<string> {
        return this.executeFunction('cm_str', [], 'string', 'required', rejectingAdapter)
    }
}

function reasonOf(e: unknown): TsSqlErrorReason | undefined {
    return e instanceof TsSqlError ? e.errorReason : undefined
}

function causeChainContains(e: unknown, target: Error): boolean {
    for (let current = e; current instanceof Error; current = current.cause) {
        if (current === target) return true
    }
    return false
}

