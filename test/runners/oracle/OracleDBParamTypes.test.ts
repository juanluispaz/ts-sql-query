// The DbType OracleDBQueryRunner binds a parameter with when its type name is
// declared in typesByName: an IN bind (read back with dump(), whose Typ is the
// type Oracle received: 12 a DATE, 180 a TIMESTAMP, 181 a TIMESTAMP WITH TIME
// ZONE) and a RETURNING OUT bind
// (the value comes back converted to that type). The pool runners pass it on
// to the runner of each connection.

import oracledb from 'oracledb'
import { afterAll, beforeAll, describe, expect, test } from '../../lib/testRunner.js'
import type { QueryRunner } from '../../../src/queryRunners/QueryRunner.js'
import { TsSqlError } from '../../../src/TsSqlError.js'
import { OracleDBQueryRunner } from '../../../src/queryRunners/OracleDBQueryRunner.js'
import { OracleDBPoolQueryRunner } from '../../../src/queryRunners/OracleDBPoolQueryRunner.js'
import { OracleDBPoolPromiseQueryRunner } from '../../../src/queryRunners/OracleDBPoolPromiseQueryRunner.js'
import { isRealDbEnabled } from '../../lib/backends.js'
import { acquireRunnerTestDatabase } from '../../db/oracle/runners.js'

describe.skipIf(!isRealDbEnabled('oracle', 'docker', 'newest', 'oracledb'))('OracleDBQueryRunner: typesByName', () => {
    let db: Awaited<ReturnType<typeof acquireRunnerTestDatabase>> | undefined
    let connection: oracledb.Connection | undefined
    let runner: QueryRunner | undefined
    let declared: QueryRunner | undefined
    const typesByName = { Day: oracledb.DB_TYPE_DATE, Code: oracledb.DB_TYPE_VARCHAR, Moment: oracledb.DB_TYPE_TIMESTAMP, Counter: oracledb.DB_TYPE_NUMBER }

    beforeAll(async () => {
        db = await acquireRunnerTestDatabase()
        connection = await oracledb.getConnection({ user: db.user, password: db.password, connectString: db.connectString })
        runner = new OracleDBQueryRunner(connection)
        declared = new OracleDBQueryRunner(connection, { typesByName })
        await runner.executeDatabaseSchemaModification("begin execute immediate 'drop table rt_typed'; exception when others then if sqlcode != -942 then raise; end if; end;")
        await runner.executeDatabaseSchemaModification('create table rt_typed (id number(10) generated by default as identity primary key, d date)')
    }, 300_000)
    afterAll(async () => {
        await runner?.executeDatabaseSchemaModification('drop table rt_typed')
        await connection?.close()
        await db?.release()
    }, 300_000)

    const day = new Date(Date.UTC(2026, 9, 25))

    async function dumpOf(r: QueryRunner, type: string): Promise<string> {
        const params: any[] = []
        const placeholder = r.addParam(params, day, type, 'customLocalDateTime', false)
        return await r.executeSelectOneColumnOneRow(`select dump(${placeholder}) from dual`, params)
    }

    test('an-in-bind-of-a-declared-type-name', async () => {
        // A local date and time goes as a TIMESTAMP, unless its type name is declared as a DATE
        expect(await dumpOf(runner!, 'Day')).toMatch(/^Typ=180 /)
        expect(await dumpOf(declared!, 'Day')).toMatch(/^Typ=12 /)
        expect(await dumpOf(declared!, 'SignOffStamp')).toMatch(/^Typ=180 /)
    })

    test('a-null-in-bind-of-a-declared-type-name', async () => {
        const params: any[] = []
        const placeholder = declared!.addParam(params, null, 'Code', 'customInt', false)
        // A VARCHAR2 null in a union with a text: a NUMBER null there is ORA-01790
        const rows = await declared!.executeSelectManyRows(`select ${placeholder} as v from dual union all select 'x' as v from dual`, params)
        expect(rows).toEqual([{ V: null }, { V: 'x' }])
    })

    test('an-out-bind-of-a-declared-type-name', async () => {
        // Without a type, oracledb returns an OUT date and an OUT number as strings
        for (const [r, expected] of [[runner!, ['string', 'string']], [declared!, ['object', 'number']]] as const) {
            const params: any[] = []
            const d = r.addParam(params, new Date(Date.UTC(2026, 9, 25)), 'localDateTime', 'localDateTime', false)
            const dOut = r.addOutParam(params, 'd', 'Moment', 'custom', false)
            const idOut = r.addOutParam(params, 'id', 'Counter', 'custom', false)
            const row = await r.executeInsertReturningOneRow(`insert into rt_typed (d) values (${d}) returning d, id into ${dOut}, ${idOut}`, params)
            expect([typeof row.d, typeof row.id]).toEqual(expected)
            if (r === declared) {
                expect(row.d).toBeInstanceOf(Date)
            }
        }
    })

    test('the-pool-runners-pass-it-on', async () => {
        const pool = await oracledb.createPool({ user: db!.user, password: db!.password, connectString: db!.connectString, poolMin: 0, poolMax: 1, stmtCacheSize: 0 })
        try {
            for (const r of [new OracleDBPoolQueryRunner(pool, { typesByName }), new OracleDBPoolPromiseQueryRunner(Promise.resolve(pool), { typesByName })]) {
                expect(await dumpOf(r, 'Day')).toMatch(/^Typ=12 /)
            }
        } finally {
            await pool.close(0)
        }
    })
})

// A date or a time compared with a column: bound as a DATE or a TIMESTAMP, the column compares as it is, and its index
// is used. Bound as a TIMESTAMP WITH TIME ZONE, Oracle would convert a DATE or a TIMESTAMP column
// (SYS_EXTRACT_UTC(INTERNAL_FUNCTION(column))), and read the whole table.
describe.skipIf(!isRealDbEnabled('oracle', 'docker', 'newest', 'oracledb'))('OracleDBQueryRunner: a date or a time compared with an indexed column', () => {
    let db: Awaited<ReturnType<typeof acquireRunnerTestDatabase>> | undefined
    let connection: oracledb.Connection | undefined
    let runner: QueryRunner | undefined

    beforeAll(async () => {
        db = await acquireRunnerTestDatabase()
        connection = await oracledb.getConnection({ user: db.user, password: db.password, connectString: db.connectString })
        runner = new OracleDBQueryRunner(connection)
        await runner.executeDatabaseSchemaModification("begin execute immediate 'drop table rt_indexed'; exception when others then if sqlcode != -942 then raise; end if; end;")
        await runner.executeDatabaseSchemaModification('create table rt_indexed (id number(10) primary key, d date, ts timestamp(3), tstz timestamp(3) with time zone, tl timestamp(3) with local time zone)')
        // An hour per row from 2024-01-01 00:00:00.123: row 10 is 2024-01-01 10:00:00.123
        await runner.executeDatabaseSchemaModification("insert into rt_indexed select level, date '2024-01-01' + level, timestamp '2024-01-01 00:00:00.123' + numtodsinterval(level, 'HOUR'), from_tz(timestamp '2024-01-01 00:00:00.123' + numtodsinterval(level, 'HOUR'), 'UTC'), timestamp '2024-01-01 00:00:00.123' + numtodsinterval(level, 'HOUR') from dual connect by level <= 2000")
        for (const column of ['d', 'ts', 'tstz', 'tl']) {
            await runner.executeDatabaseSchemaModification(`create index rt_indexed_${column} on rt_indexed(${column})`)
        }
        await runner.executeDatabaseSchemaModification("begin dbms_stats.gather_table_stats(user, 'RT_INDEXED'); end;")
    }, 300_000)
    afterAll(async () => {
        await runner?.executeDatabaseSchemaModification('drop table rt_indexed')
        await connection?.close()
        await db?.release()
    }, 300_000)

    async function idsAndPlan(column: string, value: Date, type: 'localDate' | 'localDateTime'): Promise<{ ids: unknown, index: boolean }> {
        const params: any[] = []
        const placeholder = runner!.addParam(params, value, type, type, false)
        const sql = `select id as "id" from rt_indexed where ${column} = ${placeholder}`
        const ids = (await runner!.executeSelectManyRows(sql, params)).map(row => row['id'])
        await runner!.executeUpdate('explain plan for ' + sql, params)
        const plan = await runner!.executeSelectOneColumnManyRows("select plan_table_output from table(dbms_xplan.display(null, null, 'BASIC'))", [])
        return { ids, index: plan.some(line => String(line).includes('INDEX RANGE SCAN') && String(line).toUpperCase().includes('RT_INDEXED_' + column.toUpperCase())) }
    }

    test('a-local-date-time-uses-the-index-of-a-timestamp-column', async () => {
        const value = new Date('2024-01-01T10:00:00.123Z')
        expect(await idsAndPlan('ts', value, 'localDateTime')).toEqual({ ids: [10], index: true })
        expect(await idsAndPlan('tl', value, 'localDateTime')).toEqual({ ids: [10], index: true })
        expect(await idsAndPlan('tstz', value, 'localDateTime')).toEqual({ ids: [10], index: true })
    })

    test('a-local-date-uses-the-index-of-a-date-column', async () => {
        expect(await idsAndPlan('d', new Date('2024-01-11T10:00:00.000Z'), 'localDate')).toEqual({ ids: [10], index: true })
    })
})

describe('OracleDBQueryRunner: a customDecimal parameter in hand-written SQL', () => {
    test('a-value-beyond-38-significant-digits-is-rejected', () => {
        // The number of the database keeps 38 significant digits: the runner rejects it before anything is sent, so
        // no connection is needed
        const runner = new OracleDBQueryRunner({} as oracledb.Connection)
        const params: any[] = []
        let error: unknown
        try {
            runner.addParam(params, '0.' + '1'.repeat(39), 'Amount', 'customDecimal', false)
        } catch (e) {
            error = e
        }
        expect(error instanceof TsSqlError ? error.errorReason : undefined).toEqual({ reason: 'INVALID_VALUE_TO_SEND_TO_DATABASE', value: '0.' + '1'.repeat(39), typeName: 'Amount', paramIndex: 0 })
        expect(runner.addParam(params, '0.' + '1'.repeat(38), 'Amount', 'customDecimal', false)).toBe(':0')
    })
})
