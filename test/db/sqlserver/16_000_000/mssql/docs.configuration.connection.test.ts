// Documentation snippets for the Connection page (docs/configuration/connection.md), section Quoting identifiers.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection, tAppUser } from '../../domain/connection.js'
import { ctx } from './setup.js'

class QuoteEveryIdentifierConnection extends DBConnection {
    protected override escape(identifier: string, _strict: boolean): string {
        return this.forceAsIdentifier(identifier)
    }
}

class EmailIsReservedConnection extends DBConnection {
    protected override isReservedKeyword(word: string): boolean {
        return word === 'email' || super.isReservedKeyword(word)
    }
}

// app_user.email is mapped upper-cased and written lower-cased, so it only reaches the engine through the override
// of forceAsIdentifier.
class LowerCaseQuotedIdentifierConnection extends DBConnection {
    protected override isReservedKeyword(word: string): boolean {
        return word === 'EMAIL' || super.isReservedKeyword(word)
    }
    protected override forceAsIdentifier(identifier: string): string {
        return super.forceAsIdentifier(identifier.toLowerCase())
    }
}

const tAppUserWithQuotedEmail = new class TAppUserWithQuotedEmail extends Table<DBConnection, 'TAppUserWithQuotedEmail'> {
    id    = this.autogeneratedPrimaryKey('id', 'int')
    email = this.column('EMAIL', 'string')
    constructor() { super('app_user') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:connection/quote-every-identifier', async () => {
        const expected = { id: 1, fullName: 'Ada Lovelace' }
        ctx.mockNext(expected)

        // doc-start
        const connection = ctx.withConnection(QuoteEveryIdentifierConnection)

        const user = await connection.selectFrom(tAppUser)
            .where(tAppUser.id.equals(1))
            .select({ id: tAppUser.id, fullName: tAppUser.fullName })
            .executeSelectOne()
        // doc-end

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select [id] as [id], [full_name] as [fullName] from [app_user] where [id] = @0"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof user, { id: number; fullName: string }>>()
        expect(user).toEqual(expected)
    })

    test('docs-extra:connection/is-reserved-keyword-override', async () => {
        const expected = { id: 1, email: 'ada@acme.test' }
        ctx.mockNext(expected)
        const connection = ctx.withConnection(EmailIsReservedConnection)

        const user = await connection.selectFrom(tAppUser)
            .where(tAppUser.id.equals(1))
            .select({ id: tAppUser.id, email: tAppUser.email })
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, [email] as [email] from app_user where id = @0"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof user, { id: number; email: string }>>()
        expect(user).toEqual(expected)
    })

    test('docs-extra:connection/force-as-identifier-override', async () => {
        const expected = { id: 1, email: 'ada@acme.test' }
        ctx.mockNext(expected)
        const connection = ctx.withConnection(LowerCaseQuotedIdentifierConnection)

        const user = await connection.selectFrom(tAppUserWithQuotedEmail)
            .where(tAppUserWithQuotedEmail.id.equals(1))
            .select({ id: tAppUserWithQuotedEmail.id, email: tAppUserWithQuotedEmail.email })
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, [email] as email from app_user where id = @0"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof user, { id: number; email: string }>>()
        expect(user).toEqual(expected)
    })
})
