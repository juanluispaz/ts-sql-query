// `having(columns => …)` refers to the columns of the select: each one is
// written as the same expression the select list computes (with the same
// parameters, or its alias where the database requires it), so a grouped
// expression that carries a parameter can be filtered in the having.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection, tIssue, tIssueWorklog } from '../../domain/connection.js'
import { ctx } from './setup.js'

// The issue table as a model that doesn't declare its column `title`: the database still has it.
class TIssueWithoutTitle extends Table<DBConnection, 'TIssueWithoutTitle'> {
    id       = this.autogeneratedPrimaryKey('id', 'int')
    body     = this.optionalColumn('body', 'string')
    status   = this.column('status', 'string')
    priority = this.column('priority', 'int')
    constructor() { super('issue') }
}
const tIssueWithoutTitle = new TIssueWithoutTitle()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('having-on-a-grouped-expression-with-a-parameter', async () => {
        // Priorities 2, 1, 3, 2 shifted by one: level 3 has two issues, level 4
        // one, level 2 is filtered out.
        const expected = [{ level: 3, issues: 2 }, { level: 4, issues: 1 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                level:  tIssue.priority.add(1),
                issues: connection.countAll(),
            })
            .groupBy('level')
            .having(columns => columns.level.greaterThan(2))
            .orderBy('level')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority + @0 as level, count(*) as issues from issue group by priority + @0 having (priority + @0) > @1 order by level"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            2,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ level: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-an-aggregate-of-the-select', async () => {
        const expected = [{ level: 3, issues: 2 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                level:  tIssue.priority.add(1),
                issues: connection.countAll(),
            })
            .groupBy('level')
            .having(columns => columns.issues.greaterThan(1))
            .orderBy('level')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority + @0 as level, count(*) as issues from issue group by priority + @0 having count(*) > @1 order by level"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ level: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-columns-of-a-nested-object', async () => {
        // Level 4 is the only one above 2 with a single issue.
        const expected = [{ group: { level: 4 }, issues: 1 }]
        ctx.mockNext([{ 'group.level': 4, issues: 1 }])
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                group:  { level: tIssue.priority.add(1) },
                issues: connection.countAll(),
            })
            .groupByNonAggregatedColumns()
            .having(columns => columns.group.level.greaterThan(2).and(columns.issues.equals(1)))
            .orderBy('group.level')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority + @0 as [group.level], count(*) as issues from issue group by priority + @0 having (priority + @0) > @1 and count(*) = @2 order by [group.level]"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            2,
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ group: { level: number }; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-grouped-column-referred-to-by-its-own-name', async () => {
        // Priorities 2, 1, 3, 2: the groups above 1.
        const expected = [{ priority: 2, issues: 2 }, { priority: 3, issues: 1 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                priority: tIssue.priority,
                issues:   connection.countAll(),
            })
            .groupBy('priority')
            .having(columns => columns.priority.greaterThan(1))
            .orderBy('priority')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority as priority, count(*) as issues from issue group by priority having priority > @0 order by priority"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ priority: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-column-named-like-a-different-column-of-the-group-by', async () => {
        // Grouped by the priority (2, 1, 3, 2); the column of the select named `priority` is the
        // priority modulo 2, and only the group of priority 2 has it equal to 0.
        const expected = [{ priority: 0, issues: 2 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                priority: tIssue.priority.modulo(2),
                issues:   connection.countAll(),
            })
            .groupBy(tIssue.priority)
            .having(columns => columns.priority.equals(0))
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority % @0 as priority, count(*) as issues from issue group by priority having (priority % @0) = @1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2,
            0,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ priority: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-not-using-a-column-named-like-a-different-column-of-the-group-by', async () => {
        // The same select, but the having only uses the count: the group of priority 2 is the
        // only one with two issues, and its priority modulo 2 is 0.
        const expected = [{ priority: 0, issues: 2 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                priority: tIssue.priority.modulo(2),
                issues:   connection.countAll(),
            })
            .groupBy(tIssue.priority)
            .having(columns => columns.issues.greaterThan(1))
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority % @0 as priority, count(*) as issues from issue group by priority having count(*) > @1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2,
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ priority: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-boolean-expression-of-the-select', async () => {
        // Priorities 2, 1, 3, 2: three issues above 1.
        const expected = [{ highPriority: true, issues: 3 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                highPriority: tIssue.priority.greaterThan(1),
                issues:       connection.countAll(),
            })
            .groupBy('highPriority')
            .having(columns => columns.highPriority.and(columns.issues.greaterThan(1)))
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select cast(case when priority > @0 then 1 else 0 end as bit) as highPriority, count(*) as issues from issue group by cast(case when priority > @0 then 1 else 0 end as bit) having (cast(case when priority > @0 then 1 else 0 end as bit) = 1) and count(*) > @1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ highPriority: boolean; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-the-negation-of-a-boolean-expression-of-the-select', async () => {
        // Only the issue of priority 1 is not above 1.
        const expected = [{ highPriority: false, issues: 1 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssue)
            .select({
                highPriority: tIssue.priority.greaterThan(1),
                issues:       connection.countAll(),
            })
            .groupBy('highPriority')
            .having(columns => columns.highPriority.negate())
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select cast(case when priority > @0 then 1 else 0 end as bit) as highPriority, count(*) as issues from issue group by cast(case when priority > @0 then 1 else 0 end as bit) having not ((cast(case when priority > @0 then 1 else 0 end as bit) = 1))"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ highPriority: boolean; issues: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-boolean-column-of-the-select', async () => {
        // One worklog is billable.
        const expected = [{ billable: true, worklogs: 1 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssueWorklog)
            .select({
                billable: tIssueWorklog.billable,
                worklogs: connection.countAll(),
            })
            .groupBy('billable')
            .having(columns => columns.billable)
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select billable as billable, count(*) as worklogs from issue_worklog group by billable having (billable = 1)"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof rows, Array<{ billable?: boolean; worklogs: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-boolean-column-with-a-type-adapter-of-the-select', async () => {
        // The approval is stored as 'A' / 'R'; one worklog is rejected.
        const expected = [{ approved: false, worklogs: 1 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssueWorklog)
            .select({
                approved: tIssueWorklog.approved,
                worklogs: connection.countAll(),
            })
            .groupBy('approved')
            .having(columns => columns.approved.negate())
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select cast(case approved when 'A' then 1 when 'R' then 0 else null end as bit) as approved, count(*) as worklogs from issue_worklog group by cast(case approved when 'A' then 1 when 'R' then 0 else null end as bit) having not (cast(case approved when 'A' then 1 when 'R' then 0 else null end as bit) = 1)"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof rows, Array<{ approved?: boolean; worklogs: number }>>>()
        expect(rows).toEqual(expected)
    })

    test('having-on-a-column-named-like-a-column-not-declared', async () => {
        // The table has a column `title` the model doesn't declare. Grouped by the priority
        // modulo 2 (priorities 2, 1, 3, 2): only the group of the even priorities has 0.
        const expected = [{ title: 0, issues: 2 }]
        ctx.mockNext(expected)
        const connection = ctx.conn
        const rows = await connection.selectFrom(tIssueWithoutTitle)
            .select({
                title:  tIssueWithoutTitle.priority.modulo(2),
                issues: connection.countAll(),
            })
            .groupBy('title')
            .having(columns => columns.title.equals(0))
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select priority % @0 as title, count(*) as issues from issue group by priority % @0 having (priority % @0) = @1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2,
            0,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ title: number; issues: number }>>>()
        expect(rows).toEqual(expected)
    })
})
