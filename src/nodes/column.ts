/** A column of a table, a view or values: a value source of its data type with the node of a column */
export interface DBColumnValueSource extends ValueSourceRoot, __ColumnPrivate {
    [type]: 'column'
    [writable]: true
    [hasDefaultValue]: any
}

/** A column of a table or a view: it reaches its table or view */
export const dbColumnNode: NodeStrategy<DBColumnValueSource> = {
    ...valueSourceNode,
    __toSql(vs, sqlBuilder, context) {
        return sqlBuilder._appendColumnName(vs, context)
    },
    __toSqlForCondition(vs, sqlBuilder, context) {
        return sqlBuilder._appendColumnNameForCondition(vs, context)
    },
    __registerTableOrView(vs, sqlBuilder, requiredTablesOrViews) {
        __getTableOrViewPrivate(vs.__tableOrView).__registerTableOrView(sqlBuilder, requiredTablesOrViews)
    },
    __registerRequiredColumn(vs, _sqlBuilder, requiredColumns, onlyForTablesOrViews) {
        if (onlyForTablesOrViews.has(vs.__tableOrView)) {
            requiredColumns.add(vs as any)
        }
    },
    __getOldValues(vs, sqlBuilder) {
        return __getTableOrViewPrivate(vs.__tableOrView).__getOldValues(sqlBuilder)
    },
    __getValuesForInsert(vs, sqlBuilder) {
        return __getTableOrViewPrivate(vs.__tableOrView).__getValuesForInsert(sqlBuilder)
    },
    __isAllowed(vs, sqlBuilder) {
        return __getTableOrViewPrivate(vs.__tableOrView).__isAllowed(sqlBuilder)
    },
    // A column in the definition of a table, view or values can be marked: it must remain a column
    asRequiredInOptionalObject(vs) {
        const result = Object.create(Object.getPrototypeOf(vs))
        Object.assign(result, vs)
        result.__optionalType = 'requiredInOptionalObject'
        return result
    },
}

/** A column of a table, a view or values, of the data type of its class */
export function __newDBColumn(typeClass: DataTypeClass, table: AnyTableOrView, name: string): DBColumnValueSource {
    const vs = new (typeClass as unknown as ValueSourceConstructor)('required') as DBColumnValueSource
    vs.__node = dbColumnNode
    vs.__name = name
    vs.__tableOrView = table
    vs.__hasDefault = false
    vs.__isPrimaryKey = false
    vs.__isAutogeneratedPrimaryKey = false
    vs.__isComputed = false
    vs.__writable = false
    return vs
}

// The marks of a column of a table, a view or values (a value source with the node of a column)
export function __asColumn(column: DBColumnValueSource): any {
    column.__writable = true
    return column
}

export function __asOptionalColumn(column: DBColumnValueSource): any {
    column.__writable = true
    column.__optionalType = 'optional'
    return column
}

export function __asOptional(column: DBColumnValueSource): any {
    // View counterpart to `__asOptionalColumn`: marks the optional type without flipping `__writable`. Views are
    // read-only, so their columns must not be treated as writable internally (the `extras/utils` helpers also
    // filter by table type, but column keeps the column's runtime state coherent with its public type).
    column.__optionalType = 'optional'
    return column
}

export function __asColumnWithDefaultValue(column: DBColumnValueSource): any {
    column.__writable = true
    column.__hasDefault = true
    return column
}

export function __asOptionalColumnWithDefaultValue(column: DBColumnValueSource): any {
    column.__writable = true
    column.__optionalType = 'optional'
    column.__hasDefault = true
    return column
}

export function __asAutogeneratedPrimaryKey(column: DBColumnValueSource): any {
    column.__writable = true
    column.__hasDefault = true
    column.__isPrimaryKey = true
    column.__isAutogeneratedPrimaryKey = true
    return column
}

export function __asAutogeneratedPrimaryKeyBySequence(column: DBColumnValueSource, sequenceName: string): any {
    column.__writable = true
    column.__hasDefault = true
    column.__isPrimaryKey = true
    column.__isAutogeneratedPrimaryKey = true
    column.__sequenceName = sequenceName
    return column
}

export function __asPrimaryKey(column: DBColumnValueSource): any {
    column.__writable = true
    column.__isPrimaryKey = true
    return column
}

export function __asComputedColumn(column: DBColumnValueSource): any {
    column.__isComputed = true
    return column
}

export function __asOptionalComputedColumn(column: DBColumnValueSource): any {
    column.__isComputed = true
    column.__optionalType = 'optional'
    return column
}
