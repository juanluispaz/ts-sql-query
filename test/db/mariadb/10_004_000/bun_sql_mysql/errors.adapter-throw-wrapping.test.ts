// A user TypeAdapter whose `transformValueFromDB` throws a plain `Error` (not a
// TsSqlError) while a result is being read. The library wraps it as
// INVALID_VALUE_RECEIVED_FROM_DATABASE carrying the RAW value the database
// returned (the value the adapter was handed), the type name, and — for a
// projected column — the row index and column path; the adapter's own error
// stays reachable through the `cause` chain. The read happens after the
// statement ran, so every execute method surfaces the wrapped error the same
// way, and the scenario holds on the real engine: the adapter rejects real data.
//
// The tables below remap seeded tables with a rejecting adapter on one column;
// the adapter passes values sent TO the database through unchanged.

