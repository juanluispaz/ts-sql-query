// Compile-time negative tests for UPDATE-shaped APIs on the postgres
// dialect. See `select.test.ts` for the conventions.

import { test, expect } from '../../../lib/testRunner.js'
import { Table } from '../../../../src/Table.js'
import type { DBConnection } from '../domain/connection.js'
import { tCountry, tIssue, tProject, vProjectOverview } from '../domain/connection.js'

// `connection` is type-only — the function below is checked by tsc but
// never invoked at runtime, so we don't need a real instance and don't
// open any driver-level resource just to make the file load.
declare const connection: DBConnection

// A table with a computed column and a virtual column (type-only, never executed)
// so the writability rules of set / values have a target.
class TWriteRules extends Table<DBConnection, 'TWriteRules'> {
    id        = this.autogeneratedPrimaryKey('id', 'int')
    name      = this.column('name', 'string')
    nick      = this.optionalColumn('nick', 'string')
    createdAt = this.columnWithDefaultValue('created_at', 'localDateTime')
    label     = this.computedColumn('label', 'string')
    upperName = this.virtualColumnFromFragment('string', (fragment) => fragment.sql`upper(${this.name})`)
    constructor() { super('write_rules') }
}
const tWriteRules = new TWriteRules()

function _typeNegatives() {
    // Rule: the value passed to set() must match the column's type.
    // tIssue.priority is int; passing a string is rejected.
    // @ts-expect-error priority is int, not string
    void connection.update(tIssue).set({ priority: 'high' })

    // Rule: cannot set a column that doesn't exist.
    // @ts-expect-error 'nonExistent' is not a column of tIssue
    void connection.update(tIssue).set({ nonExistent: 1 })

    // Rule: setIfValue() carries the same column-type constraint as set()
    // — only the value is widened to allow null/undefined to skip the
    // assignment.
    // @ts-expect-error priority is int, not string (setIfValue keeps the type)
    void connection.update(tIssue).setIfValue({ priority: 'high' })

    // Rule: the where clause must take a boolean value source — passing a
    // plain string is rejected.
    // @ts-expect-error string is not a boolean value source
    void connection.update(tIssue).set({ title: 'x' }).where('not-a-condition')

    // Rule: where(...) must take a BooleanValueSource. A non-boolean
    // value source (e.g. an int column reference) is rejected.
    // @ts-expect-error int column is not a boolean value source
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.priority)

    // Rule: equalsIfValue keeps the column's underlying type — passing a
    // string where int is expected is rejected (the value side is widened
    // to allow null/undefined, not to allow type widening).
    // @ts-expect-error string passed where number | null | undefined expected
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.priority.equalsIfValue('high'))

    // Rule: the columns map passed to returning({...}) cannot reference
    // properties that don't exist on the table.
    void connection.update(tProject).set({ name: 'x' }).where(tProject.id.equals(1)).returning({
        id:   tProject.id,
        // @ts-expect-error 'nonExistent' is not a column of tProject
        bad:  tProject.nonExistent,
    })

    // Rule: `tTable.oldValues()` IS typed on PostgreSqlConnection (the current
    // dialect, unlike mysql/oracle/sqlite where `oldValues()` itself is `never`),
    // but its columns are RETURNING-ONLY. They carry the `NOldValues<…>` source,
    // which `.set()` / `.where()` (keyed on the update's `USING` source) exclude —
    // so referencing an old-value column in `set()` or `where()` does not compile,
    // even though the same column IS accepted in `returning(...)`.
    const oldProject = tProject.oldValues()
    // @ts-expect-error oldValues() columns are RETURNING-only; not assignable in set()
    void connection.update(tProject).set({ name: oldProject.name }).where(tProject.id.equals(1))
    // @ts-expect-error oldValues() columns are RETURNING-only; not usable in where()
    void connection.update(tProject).set({ name: 'x' }).where(oldProject.name.equals('y'))

    // Rule: `executeUpdateNoneOrOne` / `executeUpdateOne` / `executeUpdateMany`
    // are RETURNING executors — they resolve the projected row(s), so they
    // live on the interface reached through `returning(...)` /
    // `returningOneColumn(...)`. A bare update (no RETURNING) exposes only the
    // count-only `executeUpdate(min?, max?)`; reaching any of the row-returning
    // variants without a returning clause does not compile. The runtime +
    // typed positive coverage (including the empty-set short-circuit) lives in
    // this dialect's execute-variants coverage.
    // @ts-expect-error executeUpdateNoneOrOne needs a RETURNING clause; it is not on a bare update
    void connection.update(tIssue).dynamicSet().where(tIssue.id.equals(1)).executeUpdateNoneOrOne()
    // @ts-expect-error executeUpdateOne needs a RETURNING clause; it is not on a bare update
    void connection.update(tIssue).dynamicSet().where(tIssue.id.equals(1)).executeUpdateOne()
    // @ts-expect-error executeUpdateMany needs a RETURNING clause; it is not on a bare update
    void connection.update(tIssue).dynamicSet().where(tIssue.id.equals(1)).executeUpdateMany()

    // Rule: under an active shape, the conditional `*When` set arms accept
    // only the renamed shape keys — never the real columns (same contract as
    // the non-`When` shaped set). The real column `name` is rejected by both
    // the value-map arm (`setWhen`) and the column-name arm (`keepOnlyWhen`).
    void connection.update(tProject)
        .shapedAs({ projectName: 'name' })
        .dynamicSet()
        // @ts-expect-error real column 'name' is not a shaped key on setWhen
        .setWhen(true, { name: 'x' })
    void connection.update(tProject)
        .shapedAs({ projectName: 'name', projectSlug: 'slug' })
        .set({ projectName: 'x' })
        // @ts-expect-error real column 'name' is not a shaped key on keepOnlyWhen
        .keepOnlyWhen(true, 'name')

    // Rule: under an active shape, the `disallow*` guards accept only the
    // renamed shape keys — never the real columns (same contract as the shaped
    // set / `ignore*` / `keepOnly` family, since `__sets` is keyed by the
    // renamed key). The real column is rejected by the positive-match guards
    // (`disallowIfSet`), by `disallowAnyOtherSet`, and by the conditional
    // `*When` arms.
    void connection.update(tProject)
        .shapedAs({ projectName: 'name', projectSlug: 'slug' })
        .set({ projectName: 'x' })
        // @ts-expect-error real column 'slug' is not a shaped key on disallowIfSet
        .disallowIfSet('slug is read-only', 'slug')
    void connection.update(tProject)
        .shapedAs({ projectName: 'name', projectSlug: 'slug' })
        .set({ projectName: 'x' })
        // @ts-expect-error real column 'name' is not a shaped key on disallowAnyOtherSet
        .disallowAnyOtherSet('only name', 'name')
    void connection.update(tProject)
        .shapedAs({ projectName: 'name', projectSlug: 'slug' })
        .set({ projectName: 'x' })
        // @ts-expect-error real column 'slug' is not a shaped key on disallowIfSetWhen
        .disallowIfSetWhen(true, 'slug is read-only', 'slug')

    // Rule: the target of update must be a table; a view is rejected.
    void connection.update(tProject)
    // @ts-expect-error a view is not a table, so it cannot be the target of update
    void connection.update(vProjectOverview)

    // Rule: update(...) protects against a missing where: after set(...) it is not
    // executable until where(...) is given; updateAllowingNoWhere(...) lifts that.
    void connection.updateAllowingNoWhere(tIssue).set({ title: 'x' }).executeUpdate()
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).executeUpdate()
    // @ts-expect-error update(...).set(...) without where exposes no executeUpdate
    void connection.update(tIssue).set({ title: 'x' }).executeUpdate()
    void connection.updateAllowingNoWhere(tIssue).set({ title: 'x' }).returning({ id: tIssue.id })
    // @ts-expect-error update(...).set(...) without where exposes no returning
    void connection.update(tIssue).set({ title: 'x' }).returning({ id: tIssue.id })

    // Rule: an update with nothing to set is not executable, even when no where is required.
    // @ts-expect-error updateAllowingNoWhere(...) without set exposes no executeUpdate
    void connection.updateAllowingNoWhere(tIssue).executeUpdate()

    // Rule: set(...) comes before where(...): where is not offered before set, nor set after where.
    // @ts-expect-error update(...) offers no where before set
    void connection.update(tIssue).where(tIssue.id.equals(1))
    // @ts-expect-error set is not offered after where
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).set({ status: 'closed' })

    // Rule: where(...) is given once; more conditions are added with and(...) / or(...).
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).and(tIssue.priority.equals(2))
    // @ts-expect-error a second where is not offered; use and(...)
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).where(tIssue.priority.equals(2))

    // Rule: set(...) and where(...) read only the tables of the update; a table becomes
    // readable once added with from(...).
    void connection.update(tIssue).from(tProject).set({ title: tProject.name }).where(tIssue.projectId.equals(tProject.id))
    // @ts-expect-error tProject is not part of the update, so set cannot read it
    void connection.update(tIssue).set({ title: tProject.name }).where(tIssue.id.equals(1))
    // @ts-expect-error tProject is not part of the update, so where cannot read it
    void connection.update(tIssue).set({ title: 'x' }).where(tProject.id.equals(1))
    // Rule: valuesForInsert() columns are not readable in an update.
    // @ts-expect-error valuesForInsert() columns cannot be the value of an update
    void connection.update(tIssue).set({ title: tIssue.valuesForInsert().title }).where(tIssue.id.equals(1))

    // Rule: null is accepted only by optional columns; a required column rejects it.
    void connection.update(tIssue).set({ body: null }).where(tIssue.id.equals(1))
    // @ts-expect-error `title` is a required column, so it does not accept null
    void connection.update(tIssue).set({ title: null }).where(tIssue.id.equals(1))
    // Rule: a required column needs a required value source.
    void connection.update(tIssue).set({ title: tIssue.status }).where(tIssue.id.equals(1))
    // @ts-expect-error the optional column `body` cannot be the value of the required column `title`
    void connection.update(tIssue).set({ title: tIssue.body }).where(tIssue.id.equals(1))

    // Rule: computed and virtual columns are read-only; set(...) cannot write them.
    void connection.update(tWriteRules).set({ name: 'x' }).where(tWriteRules.id.equals(1))
    // @ts-expect-error computed column `label` is not writable
    void connection.update(tWriteRules).set({ label: 'x' }).where(tWriteRules.id.equals(1))
    // @ts-expect-error virtual column `upperName` is not writable
    void connection.update(tWriteRules).set({ upperName: 'x' }).where(tWriteRules.id.equals(1))

    // Rule: connection.default() is accepted only by a column declared with a default value.
    void connection.update(tWriteRules).set({ createdAt: connection.default() }).where(tWriteRules.id.equals(1))
    // @ts-expect-error `name` has no default value, so it does not accept connection.default()
    void connection.update(tWriteRules).set({ name: connection.default() }).where(tWriteRules.id.equals(1))

    // Rule: the column names given to keepOnly(...) must be columns of the table.
    void connection.update(tIssue).set({ title: 'x' }).keepOnly('title')
    // @ts-expect-error 'nonExistent' is not a column of tIssue
    void connection.update(tIssue).set({ title: 'x' }).keepOnly('nonExistent')

    // Rule: shapedAs(...) maps each key to a column of the updated table, and the shaped
    // set(...) accepts only the shape keys, never the real column names.
    void connection.update(tIssue).shapedAs({ issueTitle: 'title' }).set({ issueTitle: 'x' })
    // @ts-expect-error 'nonExistent' is not a column of tIssue
    void connection.update(tIssue).shapedAs({ issueTitle: 'nonExistent' })
    // @ts-expect-error real column 'title' is not a shaped key on set
    void connection.update(tIssue).shapedAs({ issueTitle: 'title' }).set({ title: 'x' })
    // Rule: a shape cannot map a key to a column of a table added with from(...): only
    // the updated table is written.
    void connection.update(tIssue).from(tProject).shapedAs({ issueTitle: tIssue.title })
    // @ts-expect-error tProject.name is not a column of the updated table
    void connection.update(tIssue).from(tProject).shapedAs({ projectName: tProject.name })

    // Rule: returning(...) reads only the tables of the update; a table added with from(...) is readable.
    void connection.update(tIssue).from(tProject).set({ title: 'x' }).where(tIssue.projectId.equals(tProject.id)).returning({ n: tProject.name })
    // @ts-expect-error tProject is not part of the update, so returning cannot read it
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).returning({ n: tProject.name })
    // @ts-expect-error tProject is not part of the update, so returningOneColumn cannot read it
    void connection.update(tIssue).set({ title: 'x' }).where(tIssue.id.equals(1)).returningOneColumn(tProject.name)
    // Rule: returning(...) reads the oldValues() of the updated table only.
    void connection.update(tProject).set({ name: 'x' }).where(tProject.id.equals(1)).returning({ n: tProject.oldValues().name })
    // @ts-expect-error the oldValues() of tIssue are not readable in an update of tProject
    void connection.update(tProject).set({ name: 'x' }).where(tProject.id.equals(1)).returning({ n: tIssue.oldValues().title })
    // Positive control: oldValues() of a table whose primary key is not autogenerated.
    void connection.update(tCountry).set({ name: 'x' }).where(tCountry.code.equals('ES')).returning({ n: tCountry.oldValues().name })
}

test('update-negative-types', () => {
    expect(typeof _typeNegatives).toBe('function')
})
