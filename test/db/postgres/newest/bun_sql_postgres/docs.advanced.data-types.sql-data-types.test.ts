// Documentation snippets for the page The type of a column in the database (docs/advanced/data-types/sql-data-types.md).
// The releases of the seed: 1.2.0 signed off on 2024-01-14 at 12:30 and published on 2024-01-16 at 09:00; 1.3.0-beta.1
// not signed off; 0.9.0 signed off on 2024-02-28 at 09:00 and published on 2024-03-02 at 11:00.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import type { DBConnection } from '../../domain/connection.js'
import { Table } from '../../../../../src/Table.js'
import { withSqlDataType } from '../../../../../src/exports/v2/index.js'
import { ctx } from './setup.js'

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:sql-data-types/a-date-and-time-without-zone', async () => {
        ctx.mockNext([
            { version: '0.9.0', signedOffAt: '2024-02-28 09:00:00', signedOffHour: 9 },
            { version: '1.2.0', signedOffAt: '2024-01-14 12:30:00', signedOffHour: 12 },
        ])
        const connection = ctx.conn

        // doc-start
        const tRelease = new class TRelease extends Table<DBConnection, 'TRelease'> {
            id = this.autogeneratedPrimaryKey('id', 'int')
            version = this.column('version', 'string')
            signedOffAt = this.optionalColumn('signed_off_at', 'localDateTime', withSqlDataType({ family: 'datetime', fields: 'timestamp', timeZone: 'none' }))
            publishedAt = this.column('published_at', 'plainDateTime')
            constructor() {
                super('project_release')
            }
        }()

        const releases = await connection.selectFrom(tRelease)
            .where(tRelease.signedOffAt.toPlainDateTime().lessThan(tRelease.publishedAt))
            .select({
                version: tRelease.version,
                signedOffAt: tRelease.signedOffAt.toPlainDateTime(),
                signedOffHour: tRelease.signedOffAt.getHours(),
            })
            .orderBy('version')
            .executeSelectMany()
        // doc-end

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select version as version, signed_off_at as "signedOffAt", extract(hour from signed_off_at) as "signedOffHour" from project_release where signed_off_at < published_at order by version"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof releases, Array<{ version: string; signedOffAt?: Temporal.PlainDateTime; signedOffHour?: number }>>>()
        expect(releases.map(release => [release.version, release.signedOffAt?.toString(), release.signedOffHour])).toEqual([
            ['0.9.0', '2024-02-28T09:00:00', 9],
            ['1.2.0', '2024-01-14T12:30:00', 12],
        ])
    })
})
