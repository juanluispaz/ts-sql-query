// What OracleDBQueryRunner binds for two statements oracledb can't type by itself: the RETURNING OUT bind of a text,
// which oracledb gives a buffer of 200 bytes (NJS-016 beyond it, after the row was written), and the parameters of a
// procedure, called in PL/SQL, where a boolean is a BOOLEAN on every version of Oracle (a NUMBER is refused).

import oracledb from 'oracledb'
import { afterAll, beforeAll, describe, expect, test } from '../../lib/testRunner.js'
import { OracleDBQueryRunner, type OracleDBQueryRunnerConfig } from '../../../src/queryRunners/OracleDBQueryRunner.js'
import { isRealDbEnabled } from '../../lib/backends.js'
import { acquireRunnerTestDatabase } from '../../db/oracle/runners.js'
import { rejectionOf } from '../lib/runnerContract.js'

describe.skipIf(!isRealDbEnabled('oracle', 'docker', 'newest', 'oracledb'))('OracleDBQueryRunner: returning texts and calling procedures', () => {
    let db: Awaited<ReturnType<typeof acquireRunnerTestDatabase>> | undefined
    let connection: oracledb.Connection | undefined
    const runner = (config?: OracleDBQueryRunnerConfig) => new OracleDBQueryRunner(connection!, config)

    beforeAll(async () => {
        db = await acquireRunnerTestDatabase()
        connection = await oracledb.getConnection({ user: db.user, password: db.password, connectString: db.connectString })
        const r = runner()
        await r.executeDatabaseSchemaModification("begin execute immediate 'drop table rt_text'; exception when others then if sqlcode != -942 then raise; end if; end;")
        await r.executeDatabaseSchemaModification('create table rt_text (id number(10) generated by default as identity primary key, v varchar2(4000), c clob)')
        await r.executeDatabaseSchemaModification("begin execute immediate 'drop table rt_flag'; exception when others then if sqlcode != -942 then raise; end if; end;")
        await r.executeDatabaseSchemaModification('create table rt_flag (id number(10) generated by default as identity primary key, b number(1), n number(10))')
        await r.executeDatabaseSchemaModification('create or replace procedure rt_set_flag(p_b in boolean, p_n in number) as v number(1); begin if p_b then v := 1; elsif not p_b then v := 0; end if; insert into rt_flag (b, n) values (v, p_n); end;')
    }, 300_000)
    afterAll(async () => {
        await connection?.close()
        await db?.release()
    }, 300_000)

    function insertReturningText(r: OracleDBQueryRunner, text: string, type: string = 'string'): { sql: string, params: any[] } {
        const params: any[] = []
        const value = r.addParam(params, text, type, 'string', false)
        const out = r.addOutParam(params, 'v', type, 'string', false)
        return { sql: `insert into rt_text (v) values (${value}) returning v into ${out}`, params }
    }

    test('a-returning-of-a-text-over-200-bytes', async () => {
        const r = runner()
        for (const text of ['x'.repeat(201), 'x'.repeat(4000), 'é'.repeat(2000)]) {
            const { sql, params } = insertReturningText(r, text)
            expect(await r.executeInsertReturningOneRow(sql, params)).toEqual({ v: text })
        }
        const params: any[] = []
        const value = r.addParam(params, 'y'.repeat(3000), 'string', 'string', false)
        const out = r.addOutParam(params, 'v', 'string', 'string', false)
        const rows = await r.executeUpdateReturningManyRows(`update rt_text set v = ${value} where length(v) = 4000 returning v into ${out}`, params)
        expect(rows).toEqual([{ v: 'y'.repeat(3000) }])
    })

    test('the-returning-max-size-of-the-configuration-is-the-longest-text-returned', async () => {
        const r = runner({ returningMaxSize: 300 })
        const fits = insertReturningText(r, 'x'.repeat(300))
        expect(await r.executeInsertReturningOneRow(fits.sql, fits.params)).toEqual({ v: 'x'.repeat(300) })
        const longer = insertReturningText(r, 'x'.repeat(301))
        expect((await rejectionOf(r.executeInsertReturningOneRow(longer.sql, longer.params)) as { code?: string }).code).toBe('NJS-016')
    })

    test('a-type-name-in-types-by-name-gives-its-max-size', async () => {
        const r = runner({ returningMaxSize: 300, typesByName: { LongText: { type: oracledb.DB_TYPE_VARCHAR, maxSize: 4000 } } })
        const { sql, params } = insertReturningText(r, 'x'.repeat(4000), 'LongText')
        expect(await r.executeInsertReturningOneRow(sql, params)).toEqual({ v: 'x'.repeat(4000) })
    })

    test('a-returning-of-a-clob-declared-in-types-by-name-is-read-as-text', async () => {
        // Oracle converts a CLOB returned as a VARCHAR2 up to 4000 bytes (ORA-22835 beyond); as a CLOB, oracledb gives
        // a Lob, read as its text
        const r = runner({ typesByName: { LongText: oracledb.DB_TYPE_CLOB } })
        const text = 'z'.repeat(40000)
        const params: any[] = []
        const value = r.addParam(params, text, 'LongText', 'string', false)
        const out = r.addOutParam(params, 'c', 'LongText', 'string', false)
        expect(await r.executeInsertReturningOneRow(`insert into rt_text (c) values (${value}) returning c into ${out}`, params)).toEqual({ c: text })
    })

    test('a-procedure-takes-a-boolean-as-a-pl-sql-boolean', async () => {
        const r = runner()
        for (const [b, stored] of [[true, 1], [false, 0], [null, null]] as const) {
            const params: any[] = []
            // OracleConnection hands a boolean as 1 or 0
            const bParam = r.addParam(params, b === null ? null : Number(b), 'boolean', 'boolean', false)
            const nParam = r.addParam(params, 7, 'int', 'int', false)
            await r.executeProcedure(`begin rt_set_flag(${bParam}, ${nParam}); end;`, params)
            expect(await r.executeSelectOneRow('select b, n from rt_flag where id = (select max(id) from rt_flag)', [])).toEqual({ B: stored, N: 7 })
        }
    })

    test('a-procedure-refuses-a-boolean-for-a-number-parameter', async () => {
        const r = runner()
        const params: any[] = []
        const bParam = r.addParam(params, 1, 'boolean', 'boolean', false)
        const nParam = r.addParam(params, 1, 'boolean', 'boolean', false)
        const error = await rejectionOf(r.executeProcedure(`begin rt_set_flag(${bParam}, ${nParam}); end;`, params))
        expect(String((error as { message?: unknown }).message)).toContain('PLS-00306')
    })
})
