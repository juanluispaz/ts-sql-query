    test('docs-extra:tables-views-as-parameter/view-ref', async () => {
        function issueCount<PROJECT extends TableOrViewOf<typeof vProjectOverview, 'overview'>>(connection: DBConnection, projectRef: PROJECT) {
            const overview = fromRef(vProjectOverview, projectRef)
            return connection
                .subSelectUsing(overview)
                .from(tIssue)
                .where(tIssue.projectId.equals(overview.id))
                .selectOneColumn(connection.countAll())
                .forUseAsInlineQueryValue()
                .valueWhenNull(0)
        }

        ctx.mockNext({ name: 'Marketing site', nameUpper: 'MARKETING SITE', issues: 2 })
        const overview = vProjectOverview.as('overview')
        const row = await ctx.conn.selectFrom(overview)
            .where(overview.id.equals(1))
            .select({ name: overview.name, nameUpper: overview.nameUpper, issues: issueCount(ctx.conn, overview) })
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select overview.name as "name", upper(overview.name) as "nameUpper", nvl((select count(*) as "result" from issue where project_id = overview.id), :0) as "issues" from project_overview overview where overview.id = :1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            0,
            1,
          ]
        `)
        assertType<Exact<typeof row, { name: string; nameUpper: string; issues: number }>>()
        expect(row).toEqual({ name: 'Marketing site', nameUpper: 'MARKETING SITE', issues: 2 })
    })

