CREATE OR REPLACE FUNCTION total_view_count(p_id IN NUMBER) RETURN NUMBER AS v NUMBER; BEGIN SELECT COALESCE(SUM(view_count),0) INTO v FROM issue WHERE project_id = p_id; RETURN v; END;

