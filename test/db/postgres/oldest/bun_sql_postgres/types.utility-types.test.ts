    test('selected-values-of-a-table-is-the-select-of-all-its-columns', async () => {
        ctx.mockNext({ id: 2, version: '1.3.0-beta.1', publishedAt: new Date('2024-02-21T10:00:00Z'), notes: 'release-1.3.0-beta.1', versionTag: 'BETA', channel: 'beta' })

        const row = await ctx.conn.selectFrom(tReleaseRow)
            .select(extractColumnsFrom(tReleaseRow))
            .where(tReleaseRow.id.equals(2))
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, version as version, signing_key as "signingKey", published_at as "publishedAt", notes as notes, upper(channel) as "versionTag", channel as channel from project_release where id = $1"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2,
          ]
        `)
        assertType<Exact<typeof row, SelectedValues<typeof tReleaseRow>>>()
        assertType<Exact<SelectedRow<typeof tReleaseRow>, SelectedValues<typeof tReleaseRow>>>()
        assertType<Exact<typeof row, {
            id:          number
            version:     string
            signingKey?: string
            publishedAt: Date
            notes:       string
            versionTag:  string
            channel:     string
        }>>()
        expect(row).toEqual({ id: 2, version: '1.3.0-beta.1', publishedAt: new Date('2024-02-21T10:00:00Z'), notes: 'release-1.3.0-beta.1', versionTag: 'BETA', channel: 'beta' })
    })

    test('selected-values-projected-as-nullable-of-a-table', async () => {
        ctx.mockNext({ id: 2, version: '1.3.0-beta.1', signingKey: null })

        const row = await ctx.conn.selectFrom(tReleaseRow)
            .where(tReleaseRow.id.equals(2))
            .select({ id: tReleaseRow.id, version: tReleaseRow.version, signingKey: tReleaseRow.signingKey })
            .projectingOptionalValuesAsNullable()
            .executeSelectOne()

        const columns = { id: tReleaseRow.id, version: tReleaseRow.version, signingKey: tReleaseRow.signingKey }
        assertType<Exact<typeof row, SelectedValuesProjectedAsNullable<typeof columns>>>()
        assertType<Exact<SelectedRowProjectedAsNullable<typeof columns>, SelectedValuesProjectedAsNullable<typeof columns>>>()
        assertType<Exact<typeof row, { id: number; version: string; signingKey: string | null }>>()
        expect(row).toEqual({ id: 2, version: '1.3.0-beta.1', signingKey: null })
    })

    test('selected-values-of-a-view-with-a-virtual-column', async () => {
        ctx.mockNext({ id: 1, name: 'Marketing site', nameUpper: 'MARKETING SITE' })

        const columns = extractColumnsFrom(vProjectOverview, ['organizationId', 'organizationName', 'organizationPlan'])
        const row = await ctx.conn.selectFrom(vProjectOverview)
            .select(columns)
            .where(vProjectOverview.id.equals(1))
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, name as name, archived_at as "archivedAt", upper(name) as "nameUpper" from project_overview where id = $1"`)
        assertType<Exact<typeof row, { id: number; name: string; archivedAt?: Date; nameUpper: string }>>()
        assertType<Exact<typeof row, SelectedValues<typeof columns>>>()
        expect(row).toEqual({ id: 1, name: 'Marketing site', nameUpper: 'MARKETING SITE' })
    })

    test('selected-values-of-a-left-join-table-makes-every-column-optional', async () => {
        const manager = tOrganization.forUseInLeftJoinAs('manager')
        ctx.mockNext([{ projectId: 1 }])

        const columns = extractColumnsFrom(manager, ['verified', 'createdAt'])
        const rows = await ctx.conn.selectFrom(tProject)
            .leftOuterJoin(manager).on(manager.id.equals(tProject.organizationId).and(manager.plan.equals('no such plan')))
            .where(tProject.id.equals(1))
            .select({ projectId: tProject.id, manager: columns })
            .executeSelectMany()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project.id as "projectId", manager.id as "manager.id", manager.name as "manager.name", manager.plan as "manager.plan" from project left outer join organization as manager on manager.id = project.organization_id and manager.plan = $1 where project.id = $2"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "no such plan",
            1,
          ]
        `)
        assertType<Exact<SelectedValues<typeof columns>, { id?: number; name?: string; plan?: string }>>()
        assertType<Exact<typeof rows, Array<{ projectId: number; manager?: { id: number; name: string; plan: string } }>>>()
        expect(rows).toEqual([{ projectId: 1 }])
    })

    test('selected-values-projected-as-nullable-of-a-left-join-table', () => {
        const manager = tOrganization.forUseInLeftJoin()
        assertType<Exact<SelectedValues<typeof manager>, { id?: number; name?: string; plan?: string; verified?: boolean; createdAt?: Date }>>()
        assertType<Exact<SelectedValuesProjectedAsNullable<typeof manager>, { id: number | null; name: string | null; plan: string | null; verified: boolean | null; createdAt: Date | null }>>()
        assertType<Exact<SelectedRowProjectedAsNullable<typeof manager>, SelectedValuesProjectedAsNullable<typeof manager>>>()
        expect(Object.keys(manager).length).toBeGreaterThan(0)
    })

    test('extractors-over-a-from-ref-of-a-table-reference', async () => {
        function namesAndRow<ORG extends TableOrViewOf<typeof tOrganization, 'org'>>(connection: DBConnection, orgRef: ORG) {
            const org = fromRef(tOrganization, orgRef)
            const names = extractColumnNamesFrom(org)
            return {
                names,
                row: connection.selectFrom(org)
                    .select(extractColumnsFrom(org, ['verified', 'createdAt']))
                    .where(org.id.equals(1))
                    .executeSelectOne(),
            }
        }

        ctx.mockNext({ id: 1, name: 'Acme Corp', plan: 'pro' })
        const { names, row: pending } = namesAndRow(ctx.conn, tOrganization.as('org'))
        const row = await pending

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select org.id as id, org.name as name, org.plan as plan from organization as org where org.id = $1"`)
        assertType<Exact<typeof names, ('id' | 'name' | 'plan' | 'verified' | 'createdAt')[]>>()
        expect(sorted(names)).toEqual(['createdAt', 'id', 'name', 'plan', 'verified'])
        assertType<Exact<typeof row, { id: number; name: string; plan: string }>>()
        expect(row).toEqual({ id: 1, name: 'Acme Corp', plan: 'pro' })
    })

    test('extractors-over-a-from-ref-of-a-left-join-reference', async () => {
        function managerColumns<MANAGER extends TableOrViewLeftJoinOf<typeof tOrganization, 'manager'>>(managerRef: MANAGER) {
            const manager = fromRef(tOrganization, managerRef)
            return extractColumnsFrom(manager, ['verified', 'createdAt'])
        }

        const manager = tOrganization.forUseInLeftJoinAs('manager')
        const columns = managerColumns(manager)
        expect(sorted(Object.keys(columns))).toEqual(['id', 'name', 'plan'])

        ctx.mockNext([{ projectId: 1 }])
        const rows = await ctx.conn.selectFrom(tProject)
            .leftOuterJoin(manager).on(manager.id.equals(tProject.organizationId).and(manager.plan.equals('no such plan')))
            .where(tProject.id.equals(1))
            .select({ projectId: tProject.id, manager: columns })
            .executeSelectMany()

        assertType<Exact<typeof rows, Array<{ projectId: number; manager?: { id: number; name: string; plan: string } }>>>()
        expect(rows).toEqual([{ projectId: 1 }])
    })
