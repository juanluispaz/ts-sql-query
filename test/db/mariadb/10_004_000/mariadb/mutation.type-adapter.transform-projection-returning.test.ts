// The `transformProjection` of a type adapter writes the SQL of a value as it leaves the database, also in the
// returning of an insert, an update or a delete; its `transformValueFromDB` reads what arrives. `dayMonthYear` gives a
// release day as the text DD/MM/YYYY and reads it back as the day. `idAsText` gives an id as its text and reads it
// back as the number. Each mutation runs inside `ctx.withRollback(...)`.

