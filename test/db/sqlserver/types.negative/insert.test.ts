// Compile-time negative tests for INSERT-shaped APIs on the sqlserver dialect.
// See `select.test.ts` for the rationale and conventions.

import { test, expect } from '../../../lib/testRunner.js'
import { Table } from '../../../../src/Table.js'
import type { DBConnection } from '../domain/connection.js'
import { tIssue, tProject, tOrganization, tCountry, vProjectOverview } from '../domain/connection.js'

// `connection` is type-only — the function below is checked by tsc but
// never invoked at runtime, so we don't need a real instance and don't
// open any driver-level resource just to make the file load.
declare const connection: DBConnection

// A table with a computed column and a virtual column (type-only, never executed)
// so the writability rules of set / values have a target.
class TWriteRules extends Table<DBConnection, 'TWriteRules'> {
    id        = this.autogeneratedPrimaryKey('id', 'int')
    name      = this.column('name', 'string')
    nick      = this.optionalColumn('nick', 'string')
    createdAt = this.columnWithDefaultValue('created_at', 'localDateTime')
    label     = this.computedColumn('label', 'string')
    upperName = this.virtualColumnFromFragment('string', (fragment) => fragment.sql`upper(${this.name})`)
    constructor() { super('write_rules') }
}
const tWriteRules = new TWriteRules()

// An all-defaultable table (only an autogenerated PK) so `defaultValues()`
// types correctly.
class TDefaultsOnly extends Table<DBConnection, 'TDefaultsOnly'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    constructor() { super('defaults_only') }
}
const tDefaultsOnly = new TDefaultsOnly()

function _typeNegatives() {
    // setIfSet and setIfHasValue change what already has a value: they don't give a value to a required column
    // @ts-expect-error name and plan are still missing
    connection.insertInto(tOrganization).dynamicSet().setIfSet({ name: 'a', plan: 'p' }).executeInsert()
    // @ts-expect-error name and plan are still missing
    connection.insertInto(tOrganization).dynamicSet().setIfHasValue({ name: 'a', plan: 'p' }).executeInsert()

    // Rule: optional columns (here `body`) on an INSERT can be omitted, but
    // required columns must be present. The `status` field below is
    // required and missing, which must not compile.
    // @ts-expect-error required column `status` is missing from the INSERT
    void connection.insertInto(tIssue).values({
        projectId: 1,
        number:    1,
        title:     'x',
        priority:  1,
    })

    // Rule: column value types must match. `priority` is `int`; passing a
    // string must not compile. tsc reports the error at the offending
    // property, not at the values() call site, so the directive sits on
    // the property — see test/WRITING_TESTS.md for why this asymmetry exists.
    void connection.insertInto(tIssue).values({
        projectId: 1,
        number:    1,
        title:     'x',
        status:    'open',
        // @ts-expect-error priority is int, not string
        priority:  'high',
    })

    // Rule: cannot insert columns that don't exist on the table. tsc
    // reports the excess-property error at the property line itself —
    // directive placement matches.
    void connection.insertInto(tProject).values({
        organizationId:    1,
        name:              'x',
        slug:              'x',
        // @ts-expect-error 'nonExistentColumn' is not a column of tProject
        nonExistentColumn: 'x',
    })

    // Note: autogeneratedPrimaryKey('id', 'int') still accepts an
    // explicit id in insert values — the lib treats autogenerated as
    // "has a default" rather than "cannot be set". The schema-level
    // override holds at the SQL layer; no compile-time guard for now.
    // Rule: the conditional `disallowIfNoValueWhen(when, …)` must NOT clear a
    // missing-key obligation. `when` is a runtime value, so a column it names
    // is not statically guaranteed to have a value; the `*When` arm keeps the
    // named column in the still-missing set (like the whole `set*When` family,
    // which never narrows toward executability). Its unconditional sibling
    // `disallowIfNoValue(…)` may narrow because it throws eagerly when the
    // named column has no value.
    // Control: unconditional disallowIfNoValue narrows `projectId` out of the
    // missing set, so the later `.set(rest)` reaches an executable insert.
    void connection.insertInto(tIssue).dynamicSet()
        .disallowIfNoValue('projectId must have a value', 'projectId')
        .set({ number: 1, title: 'x', status: 'open', priority: 1 })
        .executeInsert()
    // Guard: the `*When` arm does not narrow, so `projectId` is still missing
    // after the other required columns are set and the insert is not executable.
    void connection.insertInto(tIssue).dynamicSet()
        .disallowIfNoValueWhen(false, 'projectId must have a value', 'projectId')
        .set({ number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error disallowIfNoValueWhen must not make a still-incomplete insert executable
        .executeInsert()

    // Rule: INSERT's `ignoreIfHasValue` /
    // `ignoreIfHasNoValue` accept only OPTIONAL columns
    // (`OptionalColumnsForSetOf`), whereas UPDATE's accept ALL settable columns
    // (`ColumnsForSetOf`). A REQUIRED column (`title`) is therefore rejected on
    // INSERT but accepted on UPDATE — this locks that intentional param-type
    // divergence. Control: an optional column (`body`) is accepted on INSERT.
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        .ignoreIfHasValue('body')
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error `title` is required, so it is not in OptionalColumnsForSetOf on INSERT
        .ignoreIfHasValue('title')
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error `title` is required, so it is not in OptionalColumnsForSetOf on INSERT
        .ignoreIfHasNoValue('title')
    // Positive companion — UPDATE's `ignoreIfHasValue` / `ignoreIfHasNoValue`
    // accept the same required column (ColumnsForSetOf includes required columns).
    void connection.update(tIssue).set({ title: 'x' }).ignoreIfHasValue('title')
    void connection.update(tIssue).set({ title: 'x' }).ignoreIfHasNoValue('title')

    const issueValues = { projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 }
    const projectValues = { organizationId: 1, name: 'n', slug: 's' }

    // Rule: the target of insertInto must be a table; a view is rejected.
    void connection.insertInto(tProject)
    // @ts-expect-error a view is not a table, so it cannot be the target of insertInto
    void connection.insertInto(vProjectOverview)

    // Rule: set() on a fresh insert must give every required column, like values().
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'free' })
    // @ts-expect-error required column `plan` is missing from set()
    void connection.insertInto(tOrganization).set({ name: 'x' })

    // Rule: in a multiple-row values([...]) every row must give every required column.
    void connection.insertInto(tOrganization).values([{ name: 'x', plan: 'free' }, { name: 'y', plan: 'free' }])
    // @ts-expect-error the second row is missing the required column `plan`
    void connection.insertInto(tOrganization).values([{ name: 'x', plan: 'free' }, { name: 'y' }])

    // Rule: null is accepted only by optional columns; a required column rejects it.
    void connection.insertInto(tIssue).values({ ...issueValues, body: null })
    // @ts-expect-error `title` is a required column, so it does not accept null
    void connection.insertInto(tIssue).values({ ...issueValues, title: null })

    // Rule: setIfValue() on a fresh insert still requires a value for every required
    // column; only optional columns may be given null or undefined to be skipped.
    void connection.insertInto(tIssue).setIfValue({ ...issueValues, body: null })
    // @ts-expect-error `title` is required on a fresh insert, so setIfValue cannot skip it with null
    void connection.insertInto(tIssue).setIfValue({ ...issueValues, title: null })

    // Rule: a computed column is read-only; it is not a column an insert can write.
    void connection.insertInto(tWriteRules).values({ name: 'x' })
    // @ts-expect-error computed column `label` is not writable
    void connection.insertInto(tWriteRules).values({ name: 'x', label: 'l' })
    // Rule: a virtual column (built from a fragment) is not a column an insert can write.
    // @ts-expect-error virtual column `upperName` is not writable
    void connection.insertInto(tWriteRules).values({ name: 'x', upperName: 'l' })

    // Rule: connection.default() is accepted only by a column declared with a default value.
    void connection.insertInto(tWriteRules).values({ name: 'x', createdAt: connection.default() })
    // @ts-expect-error `name` has no default value, so it does not accept connection.default()
    void connection.insertInto(tWriteRules).values({ name: connection.default() })

    // Rule: an inserted value can be a constant or a value source that needs no table;
    // a column of another table is rejected.
    void connection.insertInto(tOrganization).values({ name: connection.const('a', 'string'), plan: 'free' })
    // @ts-expect-error a column of tProject cannot be the value of an insert into tOrganization
    void connection.insertInto(tOrganization).values({ name: tProject.name, plan: 'free' })
    // Rule: a column of the table being inserted is not a value either: the row does not exist yet.
    // @ts-expect-error a column of tOrganization cannot be the value of an insert into tOrganization
    void connection.insertInto(tOrganization).values({ name: tOrganization.plan, plan: 'free' })

    // Rule: a required column needs a required value source; an optional one may be null.
    // @ts-expect-error an optional value source cannot be the value of the required column `name`
    void connection.insertInto(tOrganization).values({ name: connection.optionalConst('a', 'string'), plan: 'free' })

    // Rule: insertInto(...).from(select) needs a projection with every required column
    // of the table, each with the column's data type.
    void connection.insertInto(tOrganization).from(connection.selectFrom(tProject).select({ name: tProject.name, plan: tProject.slug }))
    // @ts-expect-error the projection is missing the required column `plan`
    void connection.insertInto(tOrganization).from(connection.selectFrom(tProject).select({ name: tProject.name }))
    // @ts-expect-error the projected `plan` is an int, but the column `plan` is a string
    void connection.insertInto(tOrganization).from(connection.selectFrom(tProject).select({ name: tProject.name, plan: tProject.id }))
    // Rule: every column of the select is a column of the table.
    // @ts-expect-error `extra` is not a column of the table
    void connection.insertInto(tOrganization).from(connection.selectFrom(tProject).select({ name: tProject.name, plan: tProject.slug, extra: tProject.id }))

    // Rule: defaultValues() is offered only when no column is required.
    void connection.insertInto(tDefaultsOnly).defaultValues()
    // @ts-expect-error tIssue has required columns, so defaultValues() is not callable
    void connection.insertInto(tIssue).defaultValues()

    // Rule: returningLastInsertedId() needs an autogenerated primary key.
    void connection.insertInto(tProject).values(projectValues).returningLastInsertedId()
    // @ts-expect-error tCountry has no autogenerated primary key, so returningLastInsertedId() is not callable
    void connection.insertInto(tCountry).values({ code: 'x', name: 'n', region: 'r' }).returningLastInsertedId()

    // Rule: returning(...) / returningOneColumn(...) read only the inserted table.
    void connection.insertInto(tProject).values(projectValues).returning({ id: tProject.id })
    // @ts-expect-error tOrganization is not part of the insert, so returning cannot read it
    void connection.insertInto(tProject).values(projectValues).returning({ n: tOrganization.name })
    // @ts-expect-error tOrganization is not part of the insert, so returningOneColumn cannot read it
    void connection.insertInto(tProject).values(projectValues).returningOneColumn(tOrganization.name)
    // Rule: an insert has no old row, so oldValues() columns are not readable in its returning.
    // @ts-expect-error oldValues() columns are not readable in the returning of an insert
    void connection.insertInto(tProject).values(projectValues).returning({ n: tProject.oldValues().name })

    // Rule: an insert with no values is not executable.
    void connection.insertInto(tProject).values(projectValues).executeInsert()
    // @ts-expect-error insertInto(...) without values exposes no executeInsert
    void connection.insertInto(tProject).executeInsert()

    // Rule: dynamicSet() / dynamicValues() stay not executable until every required column is set.
    void connection.insertInto(tIssue).dynamicSet().set({ title: 'x' }).set({ projectId: 1, number: 1, status: 'open', priority: 1 }).executeInsert()
    // @ts-expect-error projectId, number, status and priority are still missing after dynamicSet().set({ title })
    void connection.insertInto(tIssue).dynamicSet().set({ title: 'x' }).executeInsert()
    // @ts-expect-error the rows given to dynamicValues([...]) miss required columns, so the insert is not executable
    void connection.insertInto(tIssue).dynamicValues([{ title: 'x' }]).executeInsert()

    // Rule: ignoreIfSet(...) / keepOnly(...) can drop a required column, and the insert is
    // then not executable; dropping only optional columns keeps it executable.
    void connection.insertInto(tIssue).values(issueValues).ignoreIfSet('body').executeInsert()
    // @ts-expect-error ignoreIfSet('title') drops a required column, so the insert is not executable
    void connection.insertInto(tIssue).values(issueValues).ignoreIfSet('title').executeInsert()
    void connection.insertInto(tIssue).values(issueValues).keepOnly('projectId', 'number', 'title', 'status', 'priority').executeInsert()
    // @ts-expect-error keepOnly('title') drops the other required columns, so the insert is not executable
    void connection.insertInto(tIssue).values(issueValues).keepOnly('title').executeInsert()
    void connection.insertInto(tIssue).values([issueValues]).ignoreIfSet('body').executeInsert()
    // @ts-expect-error ignoreIfSet('title') on a multiple-row insert drops a required column, so it is not executable
    void connection.insertInto(tIssue).values([issueValues]).ignoreIfSet('title').executeInsert()

    // Rule: setForAll(...) on a multiple-row insert accepts null only for optional columns.
    void connection.insertInto(tIssue).values([issueValues]).setForAll({ body: null })
    // @ts-expect-error `title` is a required column, so setForAll does not accept null for it
    void connection.insertInto(tIssue).values([issueValues]).setForAll({ title: null })
}

test('insert-negative-types', () => {
    expect(typeof _typeNegatives).toBe('function')
})
