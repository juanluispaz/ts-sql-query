// A customBigint column: a bigint with a type of its own. Its values are converted as those of a bigint, read from a
// column, from the JSON of an array aggregate and back after an update, and its parameters go as bigint values with
// the customBigint category. project_release.download_count is a 64-bit integer; release 1 has 4200000042, past int32.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { getQueryParamType, getQueryParamTypeCategory } from '../../../../../src/queryRunners/QueryRunner.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

type Downloads = bigint & { readonly __brand: 'Downloads' }

const tReleaseDownloads = new class TReleaseDownloads extends Table<DBConnection, 'TReleaseDownloads'> {
    id        = this.autogeneratedPrimaryKey('id', 'int')
    projectId = this.column('project_id', 'int')
    downloads = this.optionalColumn<Downloads, 'Downloads'>('download_count', 'customBigint', 'Downloads')
    constructor() { super('project_release') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('custom-bigint/reads-compares-and-adds-as-a-bigint', async () => {
        ctx.mockNext([{ id: 1, downloads: '4200000042', next: '4200000043' }])
        const rows = await ctx.conn.selectFrom(tReleaseDownloads)
            .where(tReleaseDownloads.downloads.greaterThan(3000000000n as Downloads))
            .select({
                id: tReleaseDownloads.id,
                downloads: tReleaseDownloads.downloads,
                next: tReleaseDownloads.downloads.add(1n as Downloads),
            })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, download_count as downloads, download_count + ? as next from project_release where download_count > ? order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1n,
            3000000000n,
          ]
        `)
        const params = ctx.lastParams
        expect(params.map((_value, index) => [getQueryParamType(ctx.lastSql, params, index), getQueryParamTypeCategory(ctx.lastSql, params, index)])).toEqual([
            ['Downloads', 'customBigint'],
            ['Downloads', 'customBigint'],
        ])
        assertType<Exact<typeof rows, { id: number; downloads?: Downloads; next?: Downloads }[]>>()
        expect(rows).toEqual([{ id: 1, downloads: 4200000042n, next: 4200000043n }])
    })

    test('custom-bigint/an-array-aggregate-reads-a-bigint-from-the-json', async () => {
        ctx.mockNext([{ projectId: 1, downloads: '[4200000042]' }])
        const rows = await ctx.conn.selectFrom(tReleaseDownloads)
            .where(tReleaseDownloads.projectId.equals(1))
            .and(tReleaseDownloads.downloads.isNotNull())
            .select({
                projectId: tReleaseDownloads.projectId,
                downloads: ctx.conn.aggregateAsArrayOfOneColumn(tReleaseDownloads.downloads),
            })
            .groupBy('projectId')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project_id as projectId, cast(json_arrayagg(download_count) as char) as downloads from project_release where project_id = ? and download_count is not null group by project_id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof rows, { projectId: number; downloads: Downloads[] }[]>>()
        expect(rows).toEqual([{ projectId: 1, downloads: [4200000042n] }])
    })

    test('custom-bigint/an-update-sends-a-bigint-and-reads-it-back', async () => {
        ctx.mockNext(1)
        ctx.mockNext('9999999999')
        await ctx.withRollback(async () => {
            const updated = await ctx.conn.update(tReleaseDownloads)
                .set({ downloads: 9999999999n as Downloads })
                .where(tReleaseDownloads.id.equals(3))
                .executeUpdate()
            expect(ctx.lastSql).toMatchInlineSnapshot(`"update project_release set download_count = ? where id = ?"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                9999999999n,
                3,
              ]
            `)
            assertType<Exact<typeof updated, number>>()
            expect(updated).toBe(1)

            const downloads = await ctx.conn.selectFrom(tReleaseDownloads)
                .where(tReleaseDownloads.id.equals(3))
                .selectOneColumn(tReleaseDownloads.downloads)
                .executeSelectOne()
            assertType<Exact<typeof downloads, Downloads | null>>()
            expect(downloads).toBe(9999999999n)
        })
    })
})
