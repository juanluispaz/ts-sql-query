    test('select-column-adapter-throwing-a-plain-error-reports-the-raw-value', async () => {
        // Issue 3 is 'Migrate to ESM'.
        ctx.mockNext([{ id: 3, title: 'Migrate to ESM' }])
        let caught: unknown
        try {
            await ctx.conn.selectFrom(tIssueRejectingTitle)
                .where(tIssueRejectingTitle.id.equals(3))
                .select({ id: tIssueRejectingTitle.id, title: tIssueRejectingTitle.title })
                .executeSelectMany()
        } catch (e) { caught = e }

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, title as title from issue where id = ?"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            3,
          ]
        `)
        expect(caught).toBeInstanceOf(TsSqlQueryExecutionError)
        expect(reasonOf(caught)).toEqual({
            reason: 'INVALID_VALUE_RECEIVED_FROM_DATABASE',
            value: 'Migrate to ESM',
            typeName: 'string',
            rowIndex: 0,
            columnPath: 'title',
        })
        expect(causeChainContains(caught, adapterFailure)).toBe(true)
        expect(seenByAdapter).toEqual(['Migrate to ESM'])
    })

