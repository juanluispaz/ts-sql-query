function _typeNegatives(connection: DBConnection, money: Money) {
    // Rule: the type name of a custom type is the second generic argument.
    connection.const<Money, 'Money'>(money, 'customInt', 'Money')
    // @ts-expect-error a single generic argument does not give the type name
    connection.const<Money>(money, 'customInt', 'Money')
    connection.optionalConst<Money, 'Money'>(money, 'customInt', 'Money')
    // @ts-expect-error a single generic argument does not give the type name
    connection.optionalConst<Money>(money, 'customInt', 'Money')
    connection.fragmentWithType<Money, 'Money'>('customInt', 'Money', 'required')
    // @ts-expect-error a single generic argument does not give the type name
    connection.fragmentWithType<Money>('customInt', 'Money', 'required')
    connection.aggregateFragmentWithType<Money, 'Money'>('customInt', 'Money', 'required')
    // @ts-expect-error a single generic argument does not give the type name
    connection.aggregateFragmentWithType<Money>('customInt', 'Money', 'required')

    // Rule: the type name is part of the type: a column of the same TypeScript type
    // with another type name can be neither compared with it nor assigned to it.
    tMoney.amount.equals(connection.const<Money, 'Money'>(money, 'customInt', 'Money'))
    // @ts-expect-error another type name
    tMoney.amount.equals(tMoney.otherMoney)
    // @ts-expect-error another type name
    tMoney.amount.equals(connection.const<Money, 'OtherMoney'>(money, 'customInt', 'OtherMoney'))
    connection.update(tMoney).set({ amount: money }).where(tMoney.id.equals(1))
    // @ts-expect-error another type name
    connection.update(tMoney).set({ amount: tMoney.otherMoney }).where(tMoney.id.equals(1))
}

test('custom-type-names-negative-types', () => {
    expect(typeof _typeNegatives).toBe('function')
    expect(typeof ConnWithCustomTypes).toBe('function')
    expect(typeof VRowMoney).toBe('function')
})
