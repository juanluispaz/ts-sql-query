// The words that are written quoted when they are an identifier of a query (`_isReservedKeyword` of the SQL builder)

// Source: the keywords PostgreSQL itself classifies as reserved (R) or reserved, can be function or type (T) in
// `pg_get_keywords()`, the list behind https://www.postgresql.org/docs/current/sql-keywords-appendix.html. Each keyword
// of every category was measured unquoted as a table name, a table alias, a column name (bare and qualified) and a
// column alias in the select, insert, update, delete, on conflict, returning, with, values, group by and order by the
// library writes, on PostgreSQL 17.11, PostgreSQL 18.6 and PGlite 0.5.11 (PostgreSQL 18.6): exactly these fail (a
// syntax error, or a value function such as `user` or `current_date` read instead of the column); the non-reserved
// keywords (U and C) work unquoted in all of them. Quoting a word that doesn't need it would make it case-sensitive.
