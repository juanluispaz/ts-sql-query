function oracleReturningInto(r: QueryRunner, p: any[], names: readonly string[]) {
    return ' returning ' + names.join(', ') + ' into ' + names.map(n => r.addOutParam(p, n)).join(', ')
}

export const oracleDialect: RunnerDialect = {
    database: 'oracle',
    setup: [
        "begin execute immediate 'drop table rt_probe'; exception when others then if sqlcode != -942 then raise; end if; end;",
        "begin execute immediate 'drop table rt_auto'; exception when others then if sqlcode != -942 then raise; end if; end;",
        'create table rt_probe (id number(10) primary key, name varchar2(50) not null, amount number(10))',
        'create table rt_auto (id number(10) generated by default as identity primary key, name varchar2(50) not null)',
        'create or replace function rt_answer return number as begin return 42; end;',
        'create or replace procedure rt_touch as begin null; end;',
    ],
    fromNoTable: ' from dual',
    column: (name) => name + ' as "' + name + '"',
    connectionConfiguration: "alter session set nls_date_format = 'YYYY-MM-DD'",
    sleep: 'begin dbms_session.sleep(2); end;',
    insertReturningId: (r, p, name) => `insert into rt_auto (name) values (${r.addParam(p, name)}) returning id into ${r.addOutParam(p, '')}`,
    insertReturningRow: (r, p, id, name) => `insert into rt_probe (id, name) values (${r.addParam(p, id)}, ${r.addParam(p, name)})` + oracleReturningInto(r, p, ['id', 'name']),
    updateReturningRow: (r, p, name, minId) => `update rt_probe set name = ${r.addParam(p, name)} where id >= ${r.addParam(p, minId)}` + oracleReturningInto(r, p, ['id', 'name']),
    deleteReturningRow: (r, p, minId) => `delete from rt_probe where id >= ${r.addParam(p, minId)}` + oracleReturningInto(r, p, ['id', 'name']),
    updateReturningId: (r, p, name, minId) => `update rt_probe set name = ${r.addParam(p, name)} where id >= ${r.addParam(p, minId)}` + oracleReturningInto(r, p, ['id']),
    deleteReturningId: (r, p, minId) => `delete from rt_probe where id >= ${r.addParam(p, minId)}` + oracleReturningInto(r, p, ['id']),
    procedureCall: 'begin rt_touch(); end;',
    functionCall: 'select rt_answer() from dual',
    isolationLevels: ['read committed', 'snapshot'],
    levelWithAccessMode: false,
    accessModeAlone: true,
}

function mssqlOutput(prefix: 'inserted' | 'deleted', names: readonly string[]) {
    return ' output ' + names.map(n => prefix + '.' + n).join(', ')
}

export const sqlServerDialect: RunnerDialect = {
    database: 'sqlServer',
    setup: [
        'drop table if exists rt_probe',
        'drop table if exists rt_auto',
        'create table rt_probe (id int primary key, name nvarchar(50) not null, amount int)',
        'create table rt_auto (id int identity(1,1) primary key, name nvarchar(50) not null)',
        'create or alter function dbo.rt_answer() returns int as begin return 42 end',
        'create or alter procedure rt_touch as begin return end',
    ],
    fromNoTable: '',
    column: (name) => name,
    connectionConfiguration: 'set nocount off',
    sleep: "waitfor delay '00:00:02'",
    insertReturningId: (r, p, name) => `insert into rt_auto (name)${mssqlOutput('inserted', ['id'])} values (${r.addParam(p, name)})`,
    insertReturningIds: (r, p, names) => `insert into rt_auto (name)${mssqlOutput('inserted', ['id'])} values ${names.map(n => '(' + r.addParam(p, n) + ')').join(', ')}`,
    insertReturningRow: (r, p, id, name) => `insert into rt_probe (id, name)${mssqlOutput('inserted', ['id', 'name'])} values (${r.addParam(p, id)}, ${r.addParam(p, name)})`,
    updateReturningRow: (r, p, name, minId) => `update rt_probe set name = ${r.addParam(p, name)}${mssqlOutput('inserted', ['id', 'name'])} where id >= ${r.addParam(p, minId)}`,
    deleteReturningRow: (r, p, minId) => `delete from rt_probe${mssqlOutput('deleted', ['id', 'name'])} where id >= ${r.addParam(p, minId)}`,
    updateReturningId: (r, p, name, minId) => `update rt_probe set name = ${r.addParam(p, name)}${mssqlOutput('inserted', ['id'])} where id >= ${r.addParam(p, minId)}`,
    deleteReturningId: (r, p, minId) => `delete from rt_probe${mssqlOutput('deleted', ['id'])} where id >= ${r.addParam(p, minId)}`,
    insertReturningRows: (r, p, rows) => `insert into rt_probe (id, name)${mssqlOutput('inserted', ['id', 'name'])} values ${rows.map(row => '(' + r.addParam(p, row.id) + ', ' + r.addParam(p, row.name) + ')').join(', ')}`,
    procedureCall: 'exec rt_touch',
    functionCall: 'select dbo.rt_answer()',
    isolationLevels: ['read uncommitted', 'read committed', 'repeatable read', 'snapshot', 'serializable'],
    // The test database runs without ALLOW_SNAPSHOT_ISOLATION (see test/LIMITATIONS.md).
    levelsNotEnabled: ['snapshot'],
    levelWithAccessMode: false,
    accessModeAlone: false,
}
