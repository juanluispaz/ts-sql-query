// Documentation snippets for the Passing tables/views as parameter
// page (docs/advanced/tables-views-as-parameter.md). Demonstrates
// the type-level utilities `TableOrViewOf`, `TableOrViewLeftJoinOf`
// and `fromRef`.

import { beforeAll, afterAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact, type Extends } from '../../../../lib/assertType.js'
import { fromRef, type TableOrViewOf, type TableOrViewLeftJoinOf, type ColumnKeys } from '../../../../../src/extras/types.js'
import { tIssue, tProject, tOrganization, vProjectOverview } from '../../domain/connection.js'
import { extractColumnNamesFrom } from '../../../../../src/extras/utils.js'
import { Table } from '../../../../../src/Table.js'
import type { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

class TProjectRow extends Table<DBConnection, 'TProjectRow'> {
    id         = this.autogeneratedPrimaryKey('id', 'int')
    name       = this.column('name', 'string')
    archivedAt = this.optionalColumn('archived_at', 'localDateTime')
    constructor() { super('project') }
}
const tProjectRow = new TProjectRow()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs-extra:tables-views-as-parameter/table-or-view-of-accepts-aliased-table', () => {
        const project = tProject.as('project')
        const ref: TableOrViewOf<typeof tProject, 'project'> = project
        // ref is a typed reference; at runtime it's just the aliased table.
        expect(project).toBeDefined()
        void ref
        // The ref resolves to a bare `ITableOrView<NAlias<…>>` marker, so the
        // meaningful relationship is that the aliased table is assignable to it
        // (a full Exact against the column-bearing table is not possible).
        assertType<Extends<typeof project, TableOrViewOf<typeof tProject, 'project'>>>()
    })

    test('docs-extra:tables-views-as-parameter/table-or-view-left-join-of-typing', () => {
        const issueLJ = tIssue.forUseInLeftJoinAs('issue')
        const ref: TableOrViewLeftJoinOf<typeof tIssue, 'issue'> = issueLJ
        // Left-join refs are accepted by the type as expected.
        expect(issueLJ).toBeDefined()
        void ref
        // The left-join aliased table is assignable to its ref type.
        assertType<Extends<typeof issueLJ, TableOrViewLeftJoinOf<typeof tIssue, 'issue'>>>()
    })

    test('docs-extra:tables-views-as-parameter/from-ref-recovers-columns-from-a-ref', () => {
        const project = tProject.as('project')
        const ref: TableOrViewOf<typeof tProject, 'project'> = project
        const recovered = fromRef(tProject, ref)
        // At runtime fromRef returns its input.
        expect(recovered).toBe(project)
        expect(extractColumnNamesFrom(recovered)).toEqual(extractColumnNamesFrom(tProject))
        assertType<Exact<ColumnKeys<typeof recovered>, ColumnKeys<typeof tProject>>>()
    })

    test('docs-extra:tables-views-as-parameter/table-or-view-of-default-alias-arm', () => {
        // The default (no-alias) arm: with ALIAS defaulting to '' the type is
        // the table/view itself, so the unaliased table is assignable. Only
        // the explicit-alias arm is exercised by the tests above.
        const ref: TableOrViewOf<typeof tProject> = tProject
        void ref
        const refLJ: TableOrViewLeftJoinOf<typeof tIssue> = tIssue.forUseInLeftJoin()
        void refLJ
        // The default (no-alias) arm is the explicit `ALIAS = ''` arm.
        assertType<Exact<TableOrViewOf<typeof tProject>, TableOrViewOf<typeof tProject, ''>>>()
        assertType<Exact<TableOrViewLeftJoinOf<typeof tIssue>, TableOrViewLeftJoinOf<typeof tIssue, ''>>>()
    })

    // Smoke test of the full doc-style pattern executed end-to-end: the
    // documented generic helper builds the correlated subquery, fully typed,
    // and the outer query embeds it as an inline value.
    test('docs:tables-views-as-parameter/helper-pattern-runtime-sql-emission', async () => {
        // doc-start
        function buildIssueCountSubquery<PROJECT extends TableOrViewOf<typeof tProject, 'project'>>(connection: DBConnection, projectRef: PROJECT) {
            const project = fromRef(tProject, projectRef)

            return connection
                .subSelectUsing(project)
                .from(tIssue)
                .where(tIssue.projectId.equals(project.id))
                .selectCountAll()
                .forUseAsInlineQueryValue()
        }

        ctx.mockNext({ id: 1, name: 'Marketing site', issueCount: 2 })

        const project = tProject.as('project')

        const row = await ctx.conn.selectFrom(project)
            .where(project.id.equals(1))
            .select({
                id:         project.id,
                name:       project.name,
                issueCount: buildIssueCountSubquery(ctx.conn, project),
            })
            .executeSelectOne()
        // doc-end

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project.id as id, project.\`name\` as \`name\`, (select count(*) as result from issue where project_id = project.id) as issueCount from project as project where project.id = ?"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof row, { id: number; name: string; issueCount: number }>>()
        // project 1 (Marketing site) has issues 1 and 2 → issueCount 2
        expect(row).toEqual({ id: 1, name: 'Marketing site', issueCount: 2 })
    })

    test('docs:tables-views-as-parameter/left-join-ref', async () => {
        ctx.mockNext([{ id: 1, 'organization.id': 1, 'organization.name': 'Acme Corp' }, { id: 3 }])

        // doc-start
        function buildOrganizationProjection<ORGANIZATION extends TableOrViewLeftJoinOf<typeof tOrganization, 'organization'>>(organizationRef: ORGANIZATION) {
            const organization = fromRef(tOrganization, organizationRef)

            return {
                id:   organization.id,
                name: organization.name,
            }
        }

        const organization = tOrganization.forUseInLeftJoinAs('organization')

        const rows = await ctx.conn.selectFrom(tProject)
            .leftJoin(organization).on(organization.id.equals(tProject.organizationId).and(organization.verified))
            .where(tProject.id.in([1, 3]))
            .select({
                id:           tProject.id,
                organization: buildOrganizationProjection(organization),
            })
            .orderBy('id')
            .executeSelectMany()
        // doc-end

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project.id as id, \`organization\`.id as \`organization.id\`, \`organization\`.\`name\` as \`organization.name\` from project left join \`organization\` as \`organization\` on \`organization\`.id = project.organization_id and \`organization\`.verified = 'Y' where project.id in (?, ?) order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            3,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ id: number; organization?: { id: number; name: string } }>>>()
        // The organization of project 3 isn't verified, so the left join brings nothing.
        expect(rows).toEqual([{ id: 1, organization: { id: 1, name: 'Acme Corp' } }, { id: 3 }])
    })

    test('docs-extra:tables-views-as-parameter/table-or-view-of-without-alias-accepts-any-alias', () => {
        function nameOf<PROJECT extends TableOrViewOf<typeof tProject>>(projectRef: PROJECT) {
            return fromRef(tProject, projectRef).name
        }
        function nameOfLeftJoin<ISSUE extends TableOrViewLeftJoinOf<typeof tIssue>>(issueRef: ISSUE) {
            return fromRef(tIssue, issueRef).title
        }
        expect(nameOf(tProject)).toBeDefined()
        expect(nameOf(tProject.as('anyAlias'))).toBeDefined()
        expect(nameOfLeftJoin(tIssue.forUseInLeftJoin())).toBeDefined()
        expect(nameOfLeftJoin(tIssue.forUseInLeftJoinAs('anyAlias'))).toBeDefined()
    })

    test('docs-extra:tables-views-as-parameter/from-ref-accepts-table-class', async () => {
        function archivedOrName<PROJECT extends TableOrViewOf<typeof tProjectRow, 'p'>>(projectRef: PROJECT) {
            const project = fromRef(TProjectRow, projectRef)
            return project.archivedAt
        }

        ctx.mockNext({ id: 1, name: 'Marketing site' })
        const project = tProjectRow.as('p')
        const row = await ctx.conn.selectFrom(project)
            .where(project.id.equals(1))
            .select({ id: project.id, name: project.name, archivedAt: archivedOrName(project) })
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select \`p\`.id as id, \`p\`.\`name\` as \`name\`, \`p\`.archived_at as archivedAt from project as \`p\` where \`p\`.id = ?"`)
        assertType<Exact<typeof row, { id: number; name: string; archivedAt?: Date }>>()
        expect(row).toEqual({ id: 1, name: 'Marketing site' })
    })

    test('docs-extra:tables-views-as-parameter/left-join-ref-helper-sql', async () => {
        function organizationFields<ORG extends TableOrViewLeftJoinOf<typeof tOrganization, 'org'>>(orgRef: ORG) {
            const org = fromRef(tOrganization, orgRef)
            return { id: org.id, name: org.name, upperPlan: org.plan.toUpperCase() }
        }

        ctx.mockNext([{ id: 1, organization: { id: 1, name: 'Acme Corp', upperPlan: 'PRO' } }, { id: 3 }])
        const org = tOrganization.forUseInLeftJoinAs('org')
        const rows = await ctx.conn.selectFrom(tProject)
            .leftOuterJoin(org).on(org.id.equals(tProject.organizationId).and(org.verified))
            .where(tProject.id.in([1, 3]))
            .select({ id: tProject.id, organization: organizationFields(org) })
            .orderBy('id')
            .executeSelectMany()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project.id as id, org.id as \`organization.id\`, org.\`name\` as \`organization.name\`, upper(org.plan) as \`organization.upperPlan\` from project left outer join \`organization\` as org on org.id = project.organization_id and org.verified = 'Y' where project.id in (?, ?) order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
            3,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ id: number; organization?: { id: number; name: string; upperPlan: string } }>>>()
        // The organization of project 3 isn't verified, so the left join brings nothing.
        expect(rows).toEqual([{ id: 1, organization: { id: 1, name: 'Acme Corp', upperPlan: 'PRO' } }, { id: 3 }])
    })

    test('docs-extra:tables-views-as-parameter/view-ref', async () => {
        function issueCount<PROJECT extends TableOrViewOf<typeof vProjectOverview, 'overview'>>(connection: DBConnection, projectRef: PROJECT) {
            const overview = fromRef(vProjectOverview, projectRef)
            return connection
                .subSelectUsing(overview)
                .from(tIssue)
                .where(tIssue.projectId.equals(overview.id))
                .selectOneColumn(connection.countAll())
                .forUseAsInlineQueryValue()
                .valueWhenNull(0)
        }

        ctx.mockNext({ name: 'Marketing site', nameUpper: 'MARKETING SITE', issues: 2 })
        const overview = vProjectOverview.as('overview')
        const row = await ctx.conn.selectFrom(overview)
            .where(overview.id.equals(1))
            .select({ name: overview.name, nameUpper: overview.nameUpper, issues: issueCount(ctx.conn, overview) })
            .executeSelectOne()

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select overview.\`name\` as \`name\`, upper(overview.\`name\`) as nameUpper, ifnull((select count(*) as result from issue where project_id = overview.id), ?) as issues from project_overview as overview where overview.id = ?"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            0,
            1,
          ]
        `)
        assertType<Exact<typeof row, { name: string; nameUpper: string; issues: number }>>()
        expect(row).toEqual({ name: 'Marketing site', nameUpper: 'MARKETING SITE', issues: 2 })
    })

    test('docs-extra:tables-views-as-parameter/view-left-join-ref', async () => {
        function overviewFields<OVERVIEW extends TableOrViewLeftJoinOf<typeof vProjectOverview, 'overview'>>(ref: OVERVIEW) {
            const overview = fromRef(vProjectOverview, ref)
            return { name: overview.name, nameUpper: overview.nameUpper, archivedAt: overview.archivedAt }
        }

        ctx.mockNext({ id: 1 })
        const overview = vProjectOverview.forUseInLeftJoinAs('overview')
        const row = await ctx.conn.selectFrom(tProject)
            .leftOuterJoin(overview).on(overview.id.equals(tProject.id).and(overview.name.equals('no such project')))
            .where(tProject.id.equals(1))
            .select({ id: tProject.id, overview: overviewFields(overview) })
            .executeSelectOne()

        assertType<Exact<typeof row, { id: number; overview?: { name: string; nameUpper: string; archivedAt?: Date } }>>()
        expect(row).toEqual({ id: 1 })
    })
})
