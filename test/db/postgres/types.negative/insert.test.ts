// Compile-time negative tests for INSERT-shaped APIs on the postgres dialect.
// See `select.test.ts` for the rationale and conventions.

import { test, expect } from '../../../lib/testRunner.js'
import { Table } from '../../../../src/Table.js'
import type { DBConnection } from '../domain/connection.js'
import { tIssue, tOrganization, tProject } from '../domain/connection.js'

// `connection` is type-only — the function below is checked by tsc but
// never invoked at runtime, so we don't need a real instance and don't
// open any driver-level resource just to make the file load.
declare const connection: DBConnection

// An all-defaultable table (only an autogenerated PK) so `defaultValues()`
// types correctly — RequiredColumnsForSetOf resolves to never. Mirrors the
// TDefaultsOnly fixture in insert.default-values.test.ts.
class TDefaultsOnly extends Table<DBConnection, 'TDefaultsOnly'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    constructor() { super('defaults_only') }
}
const tDefaultsOnly = new TDefaultsOnly()

function _typeNegatives() {
    // Rule: optional columns (here `body`) on an INSERT can be omitted, but
    // required columns must be present. The `status` field below is
    // required and missing, which must not compile.
    // @ts-expect-error required column `status` is missing from the INSERT
    void connection.insertInto(tIssue).values({
        projectId: 1,
        number:    1,
        title:     'x',
        priority:  1,
    })

    // Rule: column value types must match. `priority` is `int`; passing a
    // string must not compile. tsgo reports the error at the offending
    // property, not at the values() call site, so the directive sits on
    // the property — see test/WRITING_TESTS.md for why this asymmetry exists.
    void connection.insertInto(tIssue).values({
        projectId: 1,
        number:    1,
        title:     'x',
        status:    'open',
        // @ts-expect-error priority is int, not string
        priority:  'high',
    })

    // Rule: cannot insert columns that don't exist on the table. tsgo
    // reports the excess-property error at the property line itself —
    // directive placement matches.
    void connection.insertInto(tProject).values({
        organizationId:    1,
        name:              'x',
        slug:              'x',
        // @ts-expect-error 'nonExistentColumn' is not a column of tProject
        nonExistentColumn: 'x',
    })

    // Note: autogeneratedPrimaryKey('id', 'int') still accepts an
    // explicit id in insert values — the lib treats autogenerated as
    // "has a default" rather than "cannot be set". The schema-level
    // override holds at the SQL layer; no compile-time guard for now.

    // Rule: PostgreSQL's `ON CONFLICT DO UPDATE` requires an explicit
    // conflict target — either a column list (`onConflictOn(col)`) or
    // a constraint name (`onConflictOnConstraint(name)`). The bare
    // `.onConflictDoUpdateSet({...})` / `.onConflictDoUpdateSetIfValue(...)`
    // / `.onConflictDoUpdateDynamicSet()` forms are not typed on
    // PostgreSqlConnection — calling them must not compile. Covers the
    // .set(), .values()
    // and .from(select) entry chains so a regression in any of the three
    // shapes is caught here.
    const orgSelect = connection.selectFromNoTable().select({
        name: connection.const('x', 'string'),
        plan: connection.const('pro', 'string'),
    })
    // @ts-expect-error bare onConflictDoUpdateSet on PG via .set(...) — needs onConflictOn(col)
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictDoUpdateSet({ plan: 'enterprise' })
    // @ts-expect-error bare onConflictDoUpdateSet on PG via .values([...]) — needs onConflictOn(col)
    void connection.insertInto(tOrganization).values([{ name: 'x', plan: 'pro' }]).onConflictDoUpdateSet({ plan: 'enterprise' })
    // @ts-expect-error bare onConflictDoUpdateSet on PG via .from(select) — needs onConflictOn(col)
    void connection.insertInto(tOrganization).from(orgSelect).onConflictDoUpdateSet({ plan: 'enterprise' })
    // @ts-expect-error bare onConflictDoUpdateSetIfValue on PG via .set(...) — needs onConflictOn(col)
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictDoUpdateSetIfValue({ plan: 'enterprise' })
    // @ts-expect-error bare onConflictDoUpdateDynamicSet on PG via .set(...) — needs onConflictOn(col)
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictDoUpdateDynamicSet()

    // Rule: `onConflictOnConstraint(...)` accepts only a `RawFragment`. A
    // constraint name is a SQL identifier, not a runtime value: binding it
    // as a parameter (`$N`) used to be silently accepted by the type but
    // rejected by real PostgreSQL with `ERROR: syntax error at or near
    // "$N"`. The string and `IStringValueSource` overloads have been
    // removed so the only way to supply a constraint name is via raw SQL
    // assembled from database introspection.
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictOnConstraint(connection.rawFragment`organization_name_uniq`).doNothing()
    // @ts-expect-error plain string is no longer accepted — use connection.rawFragment`...`
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictOnConstraint('organization_name_uniq')
    // @ts-expect-error IStringValueSource is no longer accepted — use connection.rawFragment`...`
    void connection.insertInto(tOrganization).set({ name: 'x', plan: 'pro' }).onConflictOnConstraint(connection.const('organization_name_uniq', 'string'))

    // Rule: after a shaped static one-shot `onConflictOn(...).doUpdateSet({renamed})`
    // the returned node stays shaped — a chained `.set(...)` and the `*When` arms
    // accept only the renamed shape keys, never the real columns.
    void connection.insertInto(tProject)
        .shapedAs({ orgId: 'organizationId', projectName: 'name', projectSlug: 'slug' })
        .set({ orgId: 1, projectName: 'a', projectSlug: 'b' })
        .onConflictOn(tProject.organizationId, tProject.slug)
        .doUpdateSet({ projectName: 'one-shot' })
        // @ts-expect-error real column 'name' is not a shaped key on the chained on-conflict set
        .set({ name: 'chained' })
    void connection.insertInto(tProject)
        .shapedAs({ orgId: 'organizationId', projectName: 'name', projectSlug: 'slug' })
        .set({ orgId: 1, projectName: 'a', projectSlug: 'b' })
        .onConflictOn(tProject.organizationId, tProject.slug)
        .doUpdateSet({ projectName: 'one-shot' })
        // @ts-expect-error real column 'name' is not a shaped key on the on-conflict setWhen
        .setWhen(true, { name: 'when' })

    // Rule: the conditional `disallowIfNoValueWhen(when, …)` must NOT clear a
    // missing-key obligation. `when` is a runtime value, so a column it names
    // is not statically guaranteed to have a value; the `*When` arm keeps the
    // named column in the still-missing set (like the whole `set*When` family,
    // which never narrows toward executability). Its unconditional sibling
    // `disallowIfNoValue(…)` may narrow because it throws eagerly when the
    // named column has no value.
    // Control: unconditional disallowIfNoValue narrows `projectId` out of the
    // missing set, so the later `.set(rest)` reaches an executable insert.
    void connection.insertInto(tIssue).dynamicSet()
        .disallowIfNoValue('projectId must have a value', 'projectId')
        .set({ number: 1, title: 'x', status: 'open', priority: 1 })
        .executeInsert()
    // Guard: the `*When` arm does not narrow, so `projectId` is still missing
    // after the other required columns are set and the insert is not executable.
    void connection.insertInto(tIssue).dynamicSet()
        .disallowIfNoValueWhen(false, 'projectId must have a value', 'projectId')
        .set({ number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error disallowIfNoValueWhen must not make a still-incomplete insert executable
        .executeInsert()

    // Rule: `executeInsertOne` is not exposed on the optional-returning path.
    // `onConflictDoNothing().returning(...)` yields an ExecutableInsertReturningOptional
    // — an ON CONFLICT DO NOTHING may insert zero rows, so "exactly one row" is unsound;
    // only executeInsertNoneOrOne / executeInsertMany are available. A plain
    // `.returning(...)` (required) does expose executeInsertOne.
    // Control: the NoneOrOne arm remains available on the optional path.
    void connection.insertInto(tOrganization).values({ name: 'x', plan: 'free' })
        .onConflictDoNothing().returning({ id: tOrganization.id }).executeInsertNoneOrOne()
    void connection.insertInto(tOrganization).values({ name: 'x', plan: 'free' })
        .onConflictDoNothing().returning({ id: tOrganization.id })
        // @ts-expect-error executeInsertOne is dropped on the optional-returning (onConflictDoNothing) path
        .executeInsertOne()
    // Same rule on the MULTI-ROW path: `.values([...])` (an array) yields the
    // Multiple-insert builder, whose `onConflictDoNothing()` can likewise suppress
    // every row — so its returning path drops `executeInsertOne` too. Control: the
    // NoneOrOne arm remains available.
    void connection.insertInto(tOrganization).values([{ name: 'x', plan: 'free' }])
        .onConflictDoNothing().returning({ id: tOrganization.id }).executeInsertNoneOrOne()
    void connection.insertInto(tOrganization).values([{ name: 'x', plan: 'free' }])
        .onConflictDoNothing().returning({ id: tOrganization.id })
        // @ts-expect-error executeInsertOne is dropped on the multi-row optional-returning (onConflictDoNothing) path
        .executeInsertOne()

    // Rule: on-conflict handling is deliberately NOT exposed off `defaultValues()`.
    // Although PostgreSQL accepts `INSERT ... DEFAULT VALUES ON CONFLICT ...`, the
    // library omits the on-conflict entry points on the defaultValues() result, so
    // calling them must not compile. Control: defaultValues() itself is valid.
    void connection.insertInto(tDefaultsOnly).defaultValues()
    void connection.insertInto(tDefaultsOnly).defaultValues()
        // @ts-expect-error on-conflict is not exposed off defaultValues()
        .onConflictDoNothing()
    void connection.insertInto(tDefaultsOnly).defaultValues()
        // @ts-expect-error on-conflict is not exposed off defaultValues()
        .onConflictOnConstraint(connection.rawFragment`x`)

    // Rule: INSERT's `ignoreIfHasValue` /
    // `ignoreIfHasNoValue` accept only OPTIONAL columns
    // (`OptionalColumnsForSetOf`), whereas UPDATE's accept ALL settable columns
    // (`ColumnsForSetOf`). A REQUIRED column (`title`) is therefore rejected on
    // INSERT but accepted on UPDATE — this locks that intentional param-type
    // divergence. Control: an optional column (`body`) is accepted on INSERT.
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        .ignoreIfHasValue('body')
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error `title` is required, so it is not in OptionalColumnsForSetOf on INSERT
        .ignoreIfHasValue('title')
    void connection.insertInto(tIssue)
        .values({ projectId: 1, number: 1, title: 'x', status: 'open', priority: 1 })
        // @ts-expect-error `title` is required, so it is not in OptionalColumnsForSetOf on INSERT
        .ignoreIfHasNoValue('title')
    // Positive companion — UPDATE's `ignoreIfHasValue` / `ignoreIfHasNoValue`
    // accept the same required column (ColumnsForSetOf includes required columns).
    void connection.update(tIssue).set({ title: 'x' }).ignoreIfHasValue('title')
    void connection.update(tIssue).set({ title: 'x' }).ignoreIfHasNoValue('title')

    // Rule: `extendShape({...})` on the shaped on-conflict dynamic set returns a
    // DE-EXECUTED node on purpose — the freshly-mapped key must be staged by a
    // following `.set(...)` before the insert is executable, so a bare
    // `.executeInsert()` right after `extendShape` must NOT typecheck. This pins
    // the intentional de-execution against a future change that re-adds `& NEXT`.
    // Control: with the intervening `.set({ archived: null })` the insert executes.
    void connection.insertInto(tProject)
        .shapedAs({ orgId: 'organizationId', projectName: 'name', projectSlug: 'slug' })
        .set({ orgId: 1, projectName: 'a', projectSlug: 'b' })
        .onConflictOn(tProject.organizationId, tProject.slug)
        .doUpdateDynamicSet({ projectName: 'Reactivated' })
        .extendShape({ archived: 'archivedAt' })
        .set({ archived: null })
        .executeInsert()
    // Guard: without the intervening `.set(...)`, the de-executed node exposes no executeInsert.
    void connection.insertInto(tProject)
        .shapedAs({ orgId: 'organizationId', projectName: 'name', projectSlug: 'slug' })
        .set({ orgId: 1, projectName: 'a', projectSlug: 'b' })
        .onConflictOn(tProject.organizationId, tProject.slug)
        .doUpdateDynamicSet({ projectName: 'Reactivated' })
        .extendShape({ archived: 'archivedAt' })
        // @ts-expect-error extendShape de-executes the shaped on-conflict node; a bare executeInsert (no intervening set) is not allowed
        .executeInsert()
}

test('insert-negative-types', () => {
    expect(typeof _typeNegatives).toBe('function')
})
