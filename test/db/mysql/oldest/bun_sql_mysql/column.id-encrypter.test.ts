    test('encrypted-id-greater-or-equal-compares-the-decrypted-number', async () => {
        // `greaterOrEqual` on the encrypted id of issue 3 sends the number 3 (a
        // bigint), so the database compares numbers, not the encrypted texts:
        // issues 3 and 4 come back, with their ids encrypted.
        const connection = ctx.withConnection(EncryptedIdConnection)
        ctx.mockNext([
            { id: 3, title: 'Migrate to ESM' },
            { id: 4, title: 'Document /v2/users' },
        ])
        const rows = await connection
            .selectFrom(tEncIssue)
            .where(tEncIssue.id.greaterOrEqual(enc(3n)))
            .select({ id: tEncIssue.id, title: tEncIssue.title })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, title as title from issue where id >= ? order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            3n,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ id: string; title: string }>>>()
        expect(rows).toEqual([
            { id: enc(3n), title: 'Migrate to ESM' },
            { id: enc(4n), title: 'Document /v2/users' },
        ])
    })

