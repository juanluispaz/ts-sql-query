class DayAsTextTypeAdapter implements TypeAdapter {
    transformValueFromDB(value: unknown, context: TypeAdapterValueFromDBContext, next: DefaultTypeAdapter): unknown {
        const parts = typeof value === 'string' ? /^(\d\d)\/(\d\d)\/(\d{4})$/.exec(value) : null
        if (parts) {
            return next.transformValueFromDB(parts[3] + '-' + parts[2] + '-' + parts[1], context)
        }
        return next.transformValueFromDB(value, context)
    }
    transformValueToDB(value: unknown, context: TypeAdapterValueToDBContext, next: DefaultTypeAdapter): unknown {
        return next.transformValueToDB(value, context)
    }
    transformProjection(sql: string, context: TypeAdapterProjectionContext, next: DefaultTypeAdapter): string {
        // Equal days give equal texts, but DD/MM/YYYY doesn't order as the day
        context.comparison = 'equality'
        if (context.output === 'resultColumn' || context.output === 'aggregatedArrayValue') {
            return "to_char(" + sql + ", 'DD/MM/YYYY')"
        }
        return next.transformProjection(sql, context)
    }
}

// project_release: 2 released on 2024-02-20 and 3 on 2024-03-01, whose texts order the other way (01/03/2024 < 20/02/2024)
const tReleaseBirthday = new class TReleaseBirthday extends Table<DBConnection, 'TReleaseBirthday'> {
    id       = this.primaryKey('id', 'int')
    birthday = this.optionalColumn<Date, 'Birthday'>('released_on', 'customLocalDate', 'Birthday', new DayAsTextTypeAdapter())
    companyId = this.column('project_id', 'int')
    constructor() { super('project_release') }
}()

// The date the text DD/MM/YYYY of the placeholder gives, in this database's SQL
function dateOfDayMonthYearText(placeholder: string): string {
    return 'to_date(' + placeholder + ", 'DD/MM/YYYY')"
}

const dayMonthYear: TypeAdapter = {
    transformValueFromDB(value, context, next) {
        return next.transformValueFromDB(value, context)
    },
    transformValueToDB(value, context, next) {
        if (value instanceof Date) {
            context.setRequestedType('string')
            const day = String(value.getUTCDate()).padStart(2, '0')
            const month = String(value.getUTCMonth() + 1).padStart(2, '0')
            return next.transformValueToDB(day + '/' + month + '/' + value.getUTCFullYear(), context)
        }
        return next.transformValueToDB(value, context)
    },
    transformPlaceholder(placeholder, context, next) {
        if (context.requestedType === 'string') {
            return dateOfDayMonthYearText(placeholder)
        }
        return next.transformPlaceholder(placeholder, context)
    },
}

const tReleaseBirthdaySentAsText = new class TReleaseBirthdaySentAsText extends Table<DBConnection, 'TReleaseBirthdaySentAsText'> {
    id = this.primaryKey('id', 'int')
    birthday = this.optionalColumn<Date, 'Birthday'>('released_on', 'customLocalDate', 'Birthday', dayMonthYear)
    constructor() {
        super('project_release')
    }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:type-adapters/global-type-adapter-placeholder', async () => {
        const color: RgbColor = { r: 1, g: 2, b: 255 }
        ctx.mockNext(1)
        ctx.mockNext({ id: 1, color: '#0102ff' })
        const connection = ctx.withConnection(RgbColorConnection)

        await ctx.withRollback(async () => {
            // doc-start
            const updatedRows = await connection.update(tOrganizationColor)
                .set({ color })
                .where(tOrganizationColor.id.equals(1))
                .executeUpdate()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update organization set plan = $1::varchar where id = $2"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "#0102ff",
                1,
              ]
            `)
            assertType<Exact<typeof updatedRows, number>>()
            expect(updatedRows).toBe(1)

            const organization = await connection.selectFrom(tOrganizationColor)
                .where(tOrganizationColor.id.equals(1))
                .select({ id: tOrganizationColor.id, color: tOrganizationColor.color })
                .executeSelectOne()

            assertType<Exact<typeof organization, { id: number; color: RgbColor }>>()
            expect(organization).toEqual({ id: 1, color })
        })
    })

    test('docs:type-adapters/transform-projection-day-as-text', async () => {
        ctx.mockNext([
            { id: 2, birthday: '20/02/2024' },
            { id: 3, birthday: '01/03/2024' },
        ])
        const connection = ctx.conn
        // doc-start
        const customers = await connection.selectFrom(tReleaseBirthday)
            .where(tReleaseBirthday.birthday.greaterOrEqual(new Date('2024-02-01')))
            .select({
                id: tReleaseBirthday.id,
                birthday: tReleaseBirthday.birthday,
            })
            .orderBy('birthday')
            .executeSelectMany()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, to_char(released_on, 'DD/MM/YYYY') as birthday from project_release where released_on >= $1 order by project_release.released_on"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2024-02-01T00:00:00.000Z,
          ]
        `)
        assertType<Exact<typeof customers, { id: number; birthday?: Date }[]>>()
        // A localDate is read as 10:00 UTC of its day
        expect(customers).toEqual([
            { id: 2, birthday: new Date('2024-02-20T10:00:00Z') },
            { id: 3, birthday: new Date('2024-03-01T10:00:00Z') },
        ])
    })

    test('docs:type-adapters/transform-projection-day-as-text-inside-json', async () => {
        // project_release: 1 and 2 of project 1, released on 2024-01-15 and 2024-02-20; 3 of project 2, on 2024-03-01
        ctx.mockNext([
            { companyId: 1, customers: JSON.stringify([{ id: 1, birthday: '15/01/2024' }, { id: 2, birthday: '20/02/2024' }]) },
            { companyId: 2, customers: JSON.stringify([{ id: 3, birthday: '01/03/2024' }]) },
        ])
        const connection = ctx.conn
        // doc-start
        const companies = await connection.selectFrom(tReleaseBirthday)
            .select({
                companyId: tReleaseBirthday.companyId,
                customers: connection.aggregateAsArray({
                    id: tReleaseBirthday.id,
                    birthday: tReleaseBirthday.birthday,
                }),
            })
            .groupBy('companyId')
            .executeSelectMany()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select project_id as "companyId", (json_agg(json_build_object('id', id, 'birthday', to_char(released_on, 'DD/MM/YYYY'))))::text as customers from project_release group by project_id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof companies, { companyId: number; customers: { id: number; birthday?: Date }[] }[]>>()
        // A localDate is read as 10:00 UTC of its day; the groups and the array have no order
        const sorted = [...companies]
            .sort((a, b) => a.companyId - b.companyId)
            .map(company => ({ ...company, customers: [...company.customers].sort((a, b) => a.id - b.id) }))
        expect(sorted).toEqual([
            { companyId: 1, customers: [
                { id: 1, birthday: new Date('2024-01-15T10:00:00Z') },
                { id: 2, birthday: new Date('2024-02-20T10:00:00Z') },
            ] },
            { companyId: 2, customers: [{ id: 3, birthday: new Date('2024-03-01T10:00:00Z') }] },
        ])
    })

    test('docs:type-adapters/exact-decimal-kept-as-text', async () => {
        const amount = '12345678901234567890.123456789' as ExactDecimal
        ctx.mockNext('12345678901234567890.123456789')
        const connection = ctx.withConnection(ExactDecimalConnection)
        // doc-start
        const result = await connection.selectFromNoTable()
            .selectOneColumn(connection.const<ExactDecimal, 'ExactDecimal'>(amount, 'customDouble', 'ExactDecimal'))
            .executeSelectOne()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select $1::numeric as result"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "12345678901234567890.123456789",
          ]
        `)
        assertType<Exact<typeof result, ExactDecimal>>()
        expect(result).toBe('12345678901234567890.123456789')
    })

    test('docs:type-adapters/requested-type-date-sent-as-text', async () => {
        ctx.mockNext([{ id: 1 }])
        const connection = ctx.conn
        // doc-start
        const customers = await connection.selectFrom(tReleaseBirthdaySentAsText)
            .where(tReleaseBirthdaySentAsText.birthday.equals(new Date('2024-01-15')))
            .select({
                id: tReleaseBirthdaySentAsText.id
            })
            .executeSelectMany()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id from project_release where released_on = to_date($1, 'DD/MM/YYYY')"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "15/01/2024",
          ]
        `)
        assertType<Exact<typeof customers, { id: number }[]>>()
        expect(customers).toEqual([{ id: 1 }])
    })

})
