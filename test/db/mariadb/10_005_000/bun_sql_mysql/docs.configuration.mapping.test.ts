// Documentation snippets for the Mapping page (docs/configuration/mapping.md), section Grouping columns.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import type { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

const tGroupedIssue = new class TGroupedIssue extends Table<DBConnection, 'TGroupedIssue'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    projectId = this.column('project_id', 'int')
    number = this.column('number', 'int')
    title = this.column('title', 'string')
    status = this.column('status', 'string')
    priority = this.column('priority', 'int')
    tracking = {
        assigneeId: this.optionalColumn('assignee_id', 'int').asRequiredInOptionalObject(),
        body: this.optionalColumn('body', 'string'),
    }
    constructor() { super('issue') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:mapping/grouping-columns-select', async () => {
        ctx.mockNext([{ id: 1, 'tracking.assigneeId': 1 }])
        const connection = ctx.conn

        // doc-start
        const issues = await connection.selectFrom(tGroupedIssue)
            .where(tGroupedIssue.tracking.assigneeId.isNotNull())
            .and(tGroupedIssue.id.equals(1))
            .select({ id: tGroupedIssue.id, tracking: tGroupedIssue.tracking })
            .executeSelectMany()
        // doc-end

        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, assignee_id as \`tracking.assigneeId\`, \`body\` as \`tracking.body\` from issue where assignee_id is not null and id = ?"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof issues, { id: number; tracking?: { assigneeId: number; body?: string } }[]>>()
        expect(issues).toEqual([{ id: 1, tracking: { assigneeId: 1 } }])
    })

    test('docs:mapping/grouping-columns-insert', async () => {
        ctx.mockNext(1000)

        await ctx.withRollback(async () => {
            const connection = ctx.conn

            // doc-start
            const issueId = await connection.insertInto(tGroupedIssue)
                .set({ projectId: 1, number: 100, title: 'Grouped', status: 'open', priority: 2, tracking: { assigneeId: 1 } })
                .returningLastInsertedId()
                .executeInsert()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"insert into issue (project_id, number, title, status, priority, assignee_id) values (?, ?, ?, ?, ?, ?) returning id"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                1,
                100,
                "Grouped",
                "open",
                2,
                1,
              ]
            `)
            assertType<Exact<typeof issueId, number>>()
            expect(typeof issueId).toBe('number')
        })
    })

    test('docs:mapping/grouping-columns-update', async () => {
        ctx.mockNext(1)

        await ctx.withRollback(async () => {
            const connection = ctx.conn

            // doc-start
            const updatedIssues = await connection.update(tGroupedIssue)
                .set({ tracking: { body: 'A comment' } })
                .where(tGroupedIssue.id.equals(1))
                .executeUpdate()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update issue set \`body\` = ? where id = ?"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "A comment",
                1,
              ]
            `)
            assertType<Exact<typeof updatedIssues, number>>()
            expect(updatedIssues).toBe(1)
        })
    })

    test('docs:mapping/grouping-columns-keep-only', async () => {
        ctx.mockNext(1)

        await ctx.withRollback(async () => {
            const connection = ctx.conn

            // doc-start
            const updatedIssues = await connection.update(tGroupedIssue)
                .dynamicSet()
                .set({ title: 'Renamed', tracking: { assigneeId: 2, body: 'A comment' } })
                .keepOnly('title', 'tracking.body')
                .where(tGroupedIssue.id.equals(1))
                .executeUpdate()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update issue set title = ?, \`body\` = ? where id = ?"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "Renamed",
                "A comment",
                1,
              ]
            `)
            assertType<Exact<typeof updatedIssues, number>>()
            expect(updatedIssues).toBe(1)
        })
    })
})
