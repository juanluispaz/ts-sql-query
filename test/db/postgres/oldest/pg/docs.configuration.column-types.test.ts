class DayAsTextTypeAdapter implements TypeAdapter {
    transformValueFromDB(value: unknown, type: string, typeCategory: TypeCategory, next: DefaultTypeAdapter): unknown {
        const parts = typeof value === 'string' ? /^(\d\d)\/(\d\d)\/(\d{4})$/.exec(value) : null
        if (parts) {
            return next.transformValueFromDB(parts[3] + '-' + parts[2] + '-' + parts[1], type, typeCategory)
        }
        return next.transformValueFromDB(value, type, typeCategory)
    }
    transformValueToDB(value: unknown, type: string, typeCategory: TypeCategory, next: DefaultTypeAdapter): unknown {
        return next.transformValueToDB(value, type, typeCategory)
    }
    transformProjection(sql: string, type: string, typeCategory: TypeCategory, output: ProjectionOutput, next: DefaultTypeAdapter): string {
        if (output === 'resultColumn') {
            return "to_char(" + sql + ", 'DD/MM/YYYY')"
        }
        return next.transformProjection(sql, type, typeCategory, output)
    }
}

// project_release: 2 released on 2024-02-20 and 3 on 2024-03-01, whose texts order the other way (01/03/2024 < 20/02/2024)
const tReleaseBirthday = new class TReleaseBirthday extends Table<DBConnection, 'TReleaseBirthday'> {
    id       = this.primaryKey('id', 'int')
    birthday = this.optionalColumn<Date, 'Birthday'>('released_on', 'customLocalDate', 'Birthday', new DayAsTextTypeAdapter())
    constructor() { super('project_release') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:column-types/global-type-adapter-placeholder', async () => {
        const color: RgbColor = { r: 1, g: 2, b: 255 }
        ctx.mockNext(1)
        ctx.mockNext({ id: 1, color: '#0102ff' })
        const connection = ctx.withConnection(RgbColorConnection)

        await ctx.withRollback(async () => {
            // doc-start
            const updatedRows = await connection.update(tOrganizationColor)
                .set({ color })
                .where(tOrganizationColor.id.equals(1))
                .executeUpdate()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update organization set plan = $1::varchar where id = $2"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "#0102ff",
                1,
              ]
            `)
            assertType<Exact<typeof updatedRows, number>>()
            expect(updatedRows).toBe(1)

            const organization = await connection.selectFrom(tOrganizationColor)
                .where(tOrganizationColor.id.equals(1))
                .select({ id: tOrganizationColor.id, color: tOrganizationColor.color })
                .executeSelectOne()

            assertType<Exact<typeof organization, { id: number; color: RgbColor }>>()
            expect(organization).toEqual({ id: 1, color })
        })
    })

    test('docs:column-types/custom-type-converted-as-its-category', async () => {
        // The SQL gives both values as text: the customInt is converted as an int, the custom arrives as it comes
        ctx.mockNext({ units: '42', tag: '42' })
        const row = await ctx.conn.selectFromNoTable()
            .select({
                units: ctx.conn.fragmentWithType<Units, 'Units'>('customInt', 'Units', 'required').sql`'42'`,
                tag: ctx.conn.fragmentWithType<string, 'Tag'>('custom', 'Tag', 'required').sql`'42'`,
            })
            .executeSelectOne()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select '42' as units, '42' as tag"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof row, { units: Units; tag: string }>>()
        expect(row).toEqual({ units: 42, tag: '42' })
    })

    test('docs:column-types/transform-projection-day-as-text', async () => {
        ctx.mockNext([
            { id: 2, birthday: '20/02/2024' },
            { id: 3, birthday: '01/03/2024' },
        ])
        const connection = ctx.conn
        // doc-start
        const customers = await connection.selectFrom(tReleaseBirthday)
            .where(tReleaseBirthday.birthday.greaterOrEqual(new Date('2024-02-01')))
            .select({
                id: tReleaseBirthday.id,
                birthday: tReleaseBirthday.birthday,
            })
            .orderBy('birthday')
            .executeSelectMany()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, to_char(released_on, 'DD/MM/YYYY') as birthday from project_release where released_on >= $1 order by project_release.released_on"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            2024-02-01T00:00:00.000Z,
          ]
        `)
        assertType<Exact<typeof customers, { id: number; birthday?: Date }[]>>()
        // A localDate is read as 10:00 UTC of its day
        expect(customers).toEqual([
            { id: 2, birthday: new Date('2024-02-20T10:00:00Z') },
            { id: 3, birthday: new Date('2024-03-01T10:00:00Z') },
        ])
    })

    test('docs:column-types/exact-decimal-kept-as-text', async () => {
        const amount = '12345678901234567890.123456789' as ExactDecimal
        ctx.mockNext('12345678901234567890.123456789')
        const connection = ctx.withConnection(ExactDecimalConnection)
        // doc-start
        const result = await connection.selectFromNoTable()
            .selectOneColumn(connection.const<ExactDecimal, 'ExactDecimal'>(amount, 'customDouble', 'ExactDecimal'))
            .executeSelectOne()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select $1::numeric as result"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "12345678901234567890.123456789",
          ]
        `)
        assertType<Exact<typeof result, ExactDecimal>>()
        expect(result).toBe('12345678901234567890.123456789')
    })

    test('docs:column-types/exact-decimals', async () => {
        ctx.mockNext([
            { id: 1, amount: '12345678901234567890.1234567891', next: '12345678901234567890.1234567892' },
            { id: 5, amount: '98765432109876543210.9876543210', next: '98765432109876543210.9876543211' },
        ])
        const connection = ctx.conn
        // doc-start
        const rows = await connection.selectFrom(tExactAmount)
            .where(tExactAmount.price.greaterThan('1'))
            .select({
                id: tExactAmount.id,
                amount: tExactAmount.amount,
                next: tExactAmount.amount.add('0.0000000001'),
            })
            .orderBy('id')
            .executeSelectMany()
        // doc-end
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as id, amount as amount, amount + $1 as next from exact_amount where price > $2 order by id"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "0.0000000001",
            "1",
          ]
        `)
        assertType<Exact<typeof rows, { id: number; amount?: string; next?: string }[]>>()
        expect(rows).toEqual([
            { id: 1, amount: '12345678901234567890.1234567891', next: '12345678901234567890.1234567892' },
            { id: 5, amount: '98765432109876543210.9876543210', next: '98765432109876543210.9876543211' },
        ])
    })
})
