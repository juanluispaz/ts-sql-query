// What the library only reads it asks for as readonly: a list given as a readonly array (`as const`, a `readonly T[]`
// kept by the application) is accepted wherever a list of values, rows, names or paths goes, with the same SQL and
// params as a mutable one.

import { describe, expect, test } from '../../lib/testRunner.js'
import { assertType, type Exact } from '../../lib/assertType.js'
import { PostgreSqlConnection } from '../../../src/connections/PostgreSqlConnection.js'
import { MockQueryRunner } from '../../../src/queryRunners/MockQueryRunner.js'
import { Table } from '../../../src/Table.js'
import { Values } from '../../../src/Values.js'
import { deepOmit, deepPick, dynamicPick, dynamicPickPaths, expandTypeFromDynamicPickPaths, extractColumnNamesFrom, extractColumnsFrom } from '../../../src/exports/v2/index.js'
import type { DynamicCondition } from '../../../src/exports/v2/index.js'

let lastQuery = ''
let lastParams: any[] = []

class DBConnection extends PostgreSqlConnection<'DBConnection'> {
    countOfItems(ids: readonly number[]) {
        const args = Object.freeze(ids.map(id => this.const(id, 'int')))
        return this.executeFunction('count_of_items', args, 'int', 'required')
    }
    archiveItems(ids: readonly number[]) {
        const args = Object.freeze(ids.map(id => this.const(id, 'int')))
        return this.executeProcedure('archive_items', args)
    }
}

class TItem extends Table<DBConnection, 'TItem'> {
    id = this.autogeneratedPrimaryKey('id', 'int')
    name = this.column('name', 'string')
    note = this.optionalColumn('note', 'string')
    constructor() { super('item') }
}

class VItemRow extends Values<DBConnection, 'vItemRow'> {
    id = this.column('int')
    name = this.column('string')
}

const conn = new DBConnection(new MockQueryRunner((type, query, params) => {
    lastQuery = query
    lastParams = params
    return type === 'executeFunction' ? 1 : type === 'insert' ? 2 : type === 'executeProcedure' ? undefined : []
}))
const tItem = new TItem()

const ids: readonly number[] = [1, 2]
const names = ['a', 'b'] as const

describe('readonly inputs', () => {
    test('in, notIn, inIfValue and notInIfValue take a readonly list', () => {
        const query = conn.selectFrom(tItem)
            .where(tItem.id.in(ids))
            .and(tItem.id.notIn(ids))
            .and(tItem.name.inIfValue(names))
            .and(tItem.name.notInIfValue(names))
            .select({ id: tItem.id })
        expect(query.query()).toBe('select id as id from item where id in ($1, $2) and id not in ($3, $4) and name in ($5, $6) and name not in ($7, $8)')
        expect(query.params()).toEqual([1, 2, 1, 2, 'a', 'b', 'a', 'b'])
        // The same as with mutable lists
        const mutableIds = [1, 2]
        const mutableNames = ['a', 'b']
        expect(conn.selectFrom(tItem)
            .where(tItem.id.in(mutableIds))
            .and(tItem.id.notIn(mutableIds))
            .and(tItem.name.inIfValue(mutableNames))
            .and(tItem.name.notInIfValue(mutableNames))
            .select({ id: tItem.id }).query()).toBe(query.query())
    })

    test('a dynamic condition takes readonly lists in its filters and in and / or', () => {
        type ItemFilter = DynamicCondition<{ id: 'int', name: 'string' }>
        const byName: ItemFilter = { name: { in: names } }
        const filter: ItemFilter = { or: [{ id: { in: ids } }, byName] as const, and: [{ name: { notIn: names } }] as const }
        const query = conn.selectFrom(tItem)
            .where(conn.dynamicConditionFor({ id: tItem.id, name: tItem.name }).withValues(filter))
            .select({ id: tItem.id })
        expect(query.query()).toBe('select id as id from item where (id in ($1, $2) or name in ($3, $4)) and name not in ($5, $6)')
        expect(query.params()).toEqual([1, 2, 'a', 'b', 'a', 'b'])
    })

    test('an insert of several rows takes a readonly list of rows', async () => {
        const rows = [{ name: 'a' }, { name: 'b' }] as const
        expect(await conn.insertInto(tItem).values(rows).executeInsert()).toBe(2)
        expect(lastQuery).toBe('insert into item (name) values ($1), ($2)')
        expect(lastParams).toEqual(['a', 'b'])
        await conn.insertInto(tItem).dynamicValues(rows).executeInsert()
        expect(lastQuery).toBe('insert into item (name) values ($1), ($2)')
    })

    test('values take a readonly list of rows', () => {
        const rows = [{ id: 1, name: 'a' }, { id: 2, name: 'b' }] as const
        const vItemRow = Values.create(VItemRow, 'vItemRow', rows)
        const query = conn.selectFrom(vItemRow).select({ id: vItemRow.id })
        expect(query.query()).toBe('with vItemRow(id, name) as (values ($1::int4, $2::text), ($3::int4, $4::text)) select id as id from vItemRow')
        expect(query.params()).toEqual([1, 'a', 2, 'b'])
        // The same as with a mutable list
        const mutableRows = [{ id: 1, name: 'a' }, { id: 2, name: 'b' }]
        const vMutableItemRow = Values.create(VItemRow, 'vItemRow', mutableRows)
        expect(conn.selectFrom(vMutableItemRow).select({ id: vMutableItemRow.id }).query()).toBe(query.query())
    })

    test('the extract functions take a readonly list of excluded columns', () => {
        const excluded = ['note'] as const
        expect(Object.keys(extractColumnsFrom(tItem, excluded))).toEqual(['id', 'name'])
        const columnNames = extractColumnNamesFrom(tItem, excluded)
        assertType<Exact<typeof columnNames, ('id' | 'name')[]>>()
        expect(columnNames).toEqual(['id', 'name'])
    })

    test('the pick functions take readonly lists of paths', () => {
        const available = { id: tItem.id, name: tItem.name, note: tItem.note }
        const mandatory = ['id'] as const
        expect(Object.keys(dynamicPick(available, { name: true }, mandatory))).toEqual(['id', 'name'])
        const paths = ['note'] as const
        expect(Object.keys(dynamicPickPaths(available, paths, mandatory))).toEqual(['id', 'note'])
        const rows = [{ id: 1, note: 'x' }]
        expect(expandTypeFromDynamicPickPaths(available, paths, rows, mandatory)).toBe(rows)
        const value = { id: 1, info: { name: 'a', note: 'x' } }
        const pickedPaths: readonly 'info.name'[] = ['info.name']
        const omittedPaths: readonly 'info.note'[] = ['info.note']
        expect(deepPick(value, pickedPaths)).toEqual({ info: { name: 'a' } })
        expect(deepOmit(value, omittedPaths)).toEqual({ id: 1, info: { name: 'a' } })
    })

    test('executeFunction and executeProcedure take a readonly list of arguments', async () => {
        expect(await conn.countOfItems(ids)).toBe(1)
        expect(lastQuery).toBe('select count_of_items($1::int4, $2::int4)')
        expect(lastParams).toEqual([1, 2])
        await conn.archiveItems(ids)
        expect(lastQuery).toBe('call archive_items($1::int4, $2::int4)')
        expect(lastParams).toEqual([1, 2])
    })
})
