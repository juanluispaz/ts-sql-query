-- col_matrix: one plain, NOT NULL column per base kind. Every
-- tColMatrix* Table / the vColMatrix View reads these SAME columns through a
-- DIFFERENT column factory; the optionality/default/computed/pk distinction is
-- type-level only. Oracle has no TIME type — localTime is carried in a TIMESTAMP
-- (mirrors project_release.cutoff_time). uuid is RAW(16) (built-in strategy).
-- Caller-provided int PK (no IDENTITY).
CREATE TABLE col_matrix (
    id NUMBER PRIMARY KEY,
    m_int NUMBER NOT NULL,
    m_bigint NUMBER(19) NOT NULL,
    m_double BINARY_DOUBLE NOT NULL,
    m_bool NUMBER(1) NOT NULL,
    m_uuid RAW(16) NOT NULL,
    m_date DATE NOT NULL,
    m_time TIMESTAMP NOT NULL,
    m_datetime TIMESTAMP NOT NULL,
    m_str VARCHAR2(64) NOT NULL
);

CREATE OR REPLACE VIEW col_matrix_view AS
SELECT id, m_int, m_bigint, m_double, m_bool, m_uuid, m_date, m_time, m_datetime, m_str
FROM col_matrix;

-- Zero-arg function per base value kind. Custom kinds reuse the
-- base-kind function. One PL/SQL block per line (blank-line separated, matching
-- the other functions). m_uuid is RAW(16); cm_uuid converts it to the hyphenated
-- string via the built-in RAW_TO_UUID (inverse of the seed's UUID_TO_RAW). Oracle
-- has no TIME/native boolean: localTime rides in TIMESTAMP, boolean in NUMBER 0/1.

CREATE OR REPLACE FUNCTION cm_int RETURN NUMBER AS v NUMBER; BEGIN SELECT m_int INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_bigint RETURN NUMBER AS v NUMBER; BEGIN SELECT m_bigint INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_double RETURN BINARY_DOUBLE AS v BINARY_DOUBLE; BEGIN SELECT m_double INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_bool RETURN NUMBER AS v NUMBER; BEGIN SELECT m_bool INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_uuid RETURN VARCHAR2 AS v VARCHAR2(36); BEGIN SELECT RAW_TO_UUID(m_uuid) INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_date RETURN DATE AS v DATE; BEGIN SELECT m_date INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_time RETURN TIMESTAMP AS v TIMESTAMP; BEGIN SELECT m_time INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_datetime RETURN TIMESTAMP AS v TIMESTAMP; BEGIN SELECT m_datetime INTO v FROM col_matrix WHERE id = 1; RETURN v; END;

CREATE OR REPLACE FUNCTION cm_str RETURN VARCHAR2 AS v VARCHAR2(64); BEGIN SELECT m_str INTO v FROM col_matrix WHERE id = 1; RETURN v; END;
