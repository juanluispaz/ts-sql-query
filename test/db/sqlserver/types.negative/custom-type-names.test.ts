    columnOne = this.column<Money>('amount', 'customInt', 'Money')
    // @ts-expect-error a single generic argument does not give the type name
    optionalColumnOne = this.optionalColumn<Money>('amount', 'customInt', 'Money')
    // @ts-expect-error a single generic argument does not give the type name
