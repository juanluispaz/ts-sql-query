// Compile-time negative tests for the type name of a custom type on the sqlserver
// dialect: it is given as the second generic argument, and a single generic
// argument does not compile. These never execute any SQL: `validate:tests` (tsc)
// rejects each `@ts-expect-error` line.

import { test, expect } from '../../../lib/testRunner.js'
import { Table } from '../../../../src/Table.js'
import { View } from '../../../../src/View.js'
import { Values } from '../../../../src/Values.js'
import { DBConnection } from '../domain/connection.js'

type Money = number & { readonly __money: unique symbol }

// The methods of the connection that are protected are only reachable in a subclass.
class ConnWithCustomTypes extends DBConnection {
    // Rule: the type name of a custom type is the second generic argument.
    sequenceTwo = this.sequence<Money, 'Money'>('money_seq', 'customInt', 'Money')
    // @ts-expect-error a single generic argument does not give the type name
    sequenceOne = this.sequence<Money>('money_seq', 'customInt', 'Money')

    callTwo() { return this.executeFunction<Money, 'Money'>('money_fn', [], 'customInt', 'Money', 'required') }
    // @ts-expect-error a single generic argument does not give the type name
    callOne() { return this.executeFunction<Money>('money_fn', [], 'customInt', 'Money', 'required') }

    argTwo() { return this.arg<Money, 'Money'>('customInt', 'Money', 'required') }
    // @ts-expect-error a single generic argument does not give the type name
    argOne() { return this.arg<Money>('customInt', 'Money', 'required') }

    valueArgTwo() { return this.valueArg<Money, 'Money'>('customInt', 'Money', 'required') }
    // @ts-expect-error a single generic argument does not give the type name
    valueArgOne() { return this.valueArg<Money>('customInt', 'Money', 'required') }
}

