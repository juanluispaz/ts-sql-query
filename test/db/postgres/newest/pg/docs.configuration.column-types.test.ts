//
// The page stores the color in a binary column; organization.plan holds it here as a hex string, which keeps the
// round trip through the connection on every database.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

interface RgbColor { r: number, g: number, b: number }

function isRgbColor(value: object): value is RgbColor {
    return 'r' in value && 'g' in value && 'b' in value
}

function toHexPair(value: number): string {
    return value.toString(16).padStart(2, '0')
}

class RgbColorConnection extends DBConnection {
    protected override transformValueFromDB(value: unknown, type: string) {
        if (type === 'RgbColor' && value) {
            if (typeof value === 'string' && value.length === 7) {
                return { r: parseInt(value.slice(1, 3), 16), g: parseInt(value.slice(3, 5), 16), b: parseInt(value.slice(5, 7), 16) }
            }
            throw new Error(`Cannot decode database value ${String(value)} (type ${typeof value}) as RgbColor`)
        }
        return super.transformValueFromDB(value, type)
    }
    protected override transformValueToDB(value: unknown, type: string) {
        if (type === 'RgbColor' && value) {
            if (typeof value === 'object' && isRgbColor(value)) {
                return `#${toHexPair(value.r)}${toHexPair(value.g)}${toHexPair(value.b)}`
            }
            throw new Error(`Cannot encode value ${String(value)} for database`)
        }
        return super.transformValueToDB(value, type)
    }
    protected override transformPlaceholder(placeholder: string, type: string, forceTypeCast: boolean, valueSentToDB: unknown): string {
        if (type === 'RgbColor') {
            return placeholder + '::varchar'
        }
        return super.transformPlaceholder(placeholder, type, forceTypeCast, valueSentToDB)
    }
}

const tOrganizationColor = new class TOrganizationColor extends Table<DBConnection, 'TOrganizationColor'> {
    id    = this.autogeneratedPrimaryKey('id', 'int')
    color = this.column<RgbColor, 'RgbColor'>('plan', 'custom', 'RgbColor')
    constructor() { super('organization') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('docs:column-types/global-type-adapter-placeholder', async () => {
        const color: RgbColor = { r: 1, g: 2, b: 255 }
        ctx.mockNext(1)
        ctx.mockNext({ id: 1, color: '#0102ff' })
        const connection = ctx.withConnection(RgbColorConnection)

        await ctx.withRollback(async () => {
            // doc-start
            const updatedRows = await connection.update(tOrganizationColor)
                .set({ color })
                .where(tOrganizationColor.id.equals(1))
                .executeUpdate()
            // doc-end

            expect(ctx.lastSql).toMatchInlineSnapshot(`"update organization set plan = $1::varchar where id = $2"`)
            expect(ctx.lastParams).toMatchInlineSnapshot(`
              [
                "#0102ff",
                1,
              ]
            `)
            assertType<Exact<typeof updatedRows, number>>()
            expect(updatedRows).toBe(1)

            const organization = await connection.selectFrom(tOrganizationColor)
                .where(tOrganizationColor.id.equals(1))
                .select({ id: tOrganizationColor.id, color: tOrganizationColor.color })
                .executeSelectOne()

            assertType<Exact<typeof organization, { id: number; color: RgbColor }>>()
            expect(organization).toEqual({ id: 1, color })
        })
    })
})
