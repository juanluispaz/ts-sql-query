import type { AnyTableOrView, HasIsValue, IQueryDataDiscovery, IWithView } from '../utils/ITableOrView.js'
import { __addWiths, __registerRequiredColumn, __registerTableOrView } from '../utils/ITableOrView.js'
import type { DBColumn } from '../utils/Column.js'
import type { RawFragment } from '../utils/RawFragment.js'
import type { isTableOrViewObject } from '../utils/symbols.js'

/**
 * A table, a view, values or a `with` at run time: the class each of them extends (Table, View and Values through a cast
 * TypeScript doesn't see, so their public types have only what they declare). It has what they share: the name, the
 * alias, the customization, and what the query reaches through them. A field that only some of them have exists only
 * when it is given (`declare`, no initial value).
 */
export abstract class TableOrViewRoot implements IQueryDataDiscovery {
    /** The mark of a table or view for TypeScript (AnyTableOrView); nothing at run time */
    declare readonly [isTableOrViewObject]: true

    __name: string
    /** The alias: a copy made by `as`, `forUseInLeftJoinAs`, `oldValues` or `valuesForInsert` */
    declare __as?: string | undefined
    /** A copy made by `forUseInLeftJoin` / `forUseInLeftJoinAs` */
    declare __forUseInLeftJoin?: boolean | undefined
    /** The name was generated by the library (a recursive select): it is written with the name it has in the query */
    declare __generatedName?: boolean | undefined
    /** A customized table or view (`createTableOrViewCustomization`): its SQL, its name, and how a copy gets it again */
    declare __template?: RawFragment<any> | undefined
    declare __customizationName?: string | undefined
    declare __customizationApply?: ((target: AnyTableOrView) => void) | undefined
    /** The old values of an update (`oldValues()`) */
    declare __oldValues?: boolean | undefined
    /** The values of an insert (`valuesForInsert()`) */
    declare __valuesForInsert?: boolean | undefined
    /** A `with` whose select uses tables of the query around it */
    declare __hasExternalDependencies?: boolean | undefined

    constructor(name: string) {
        this.__name = name
    }

    __addWiths(sqlBuilder: HasIsValue, withs: Array<IWithView<any>>): void {
        __addWiths(this.__template, sqlBuilder, withs)
    }
    __registerTableOrView(sqlBuilder: HasIsValue, requiredTablesOrViews: Set<AnyTableOrView>): void {
        requiredTablesOrViews.add(this)
        __registerTableOrView(this.__template, sqlBuilder, requiredTablesOrViews)
    }
    __registerRequiredColumn(sqlBuilder: HasIsValue, requiredColumns: Set<DBColumn>, onlyForTablesOrViews: Set<AnyTableOrView>): void {
        __registerRequiredColumn(this.__template, sqlBuilder, requiredColumns, onlyForTablesOrViews)
    }
    __getOldValues(_sqlBuilder: HasIsValue): AnyTableOrView | undefined {
        return this.__oldValues ? this : undefined
    }
    __getValuesForInsert(_sqlBuilder: HasIsValue): AnyTableOrView | undefined {
        return this.__valuesForInsert ? this : undefined
    }
    __isAllowed(_sqlBuilder: HasIsValue): boolean {
        return true
    }
    __hasAggregation(_sqlBuilder: HasIsValue): boolean {
        return false
    }
}

/** A table, view, values or `with` of the public types as it is at run time */
export function __asTableOrViewRoot(tableOrView: AnyTableOrView | object): TableOrViewRoot {
    return tableOrView as TableOrViewRoot
}

/** Whether the value is a table, a view, values or a `with` */
export function __isTableOrView(value: unknown): value is TableOrViewRoot {
    return value instanceof TableOrViewRoot
}

/** The class of a public table, view or values extends TableOrViewRoot without TypeScript seeing it */
export const TableOrViewRuntime = TableOrViewRoot as unknown as abstract new (name: string) => object
