import type { AnyTableOrView } from '../utils/ITableOrView.js'
import { __registerTableOrView } from '../utils/ITableOrView.js'
import type { DBColumn } from '../utils/Column.js'
import { valueSourceNode, type NodeStrategy, type NodeValueSource, __copyOfValueSource, type InCreation } from './NodeStrategy.js'
import { type ValueSourceConstructor } from './dataTypeClassOf.js'
import type { DataTypeClass } from '../TypeAdapter.js'
import { __asTableOrViewRoot } from '../internal/TableOrViewRoot.js'

/**
 * A column of a table, a view or values: a value source of its data type with the node of a column, and the marks its
 * table, view or values gave it
 */
export interface DBColumnValueSource extends NodeValueSource, DBColumn {
    readonly __name: string
    readonly __tableOrView: AnyTableOrView
    /** Whether the column receives a value in an insert, an update or a row of values */
    readonly __writable: boolean
    readonly __hasDefault: boolean
    readonly __isPrimaryKey: boolean
    readonly __isAutogeneratedPrimaryKey: boolean
    /** Whether the database computes the value of the column */
    readonly __isComputed: boolean
    readonly __sequenceName?: string | undefined
}

/** A column of the public types as it is at run time */
export function __asDBColumnValueSource(column: DBColumn): DBColumnValueSource {
    return column as unknown as DBColumnValueSource
}

/** A column of a table or a view: it reaches its table or view */
export const dbColumnNode: NodeStrategy<DBColumnValueSource> = {
    ...valueSourceNode,
    __toSql(vs, sqlBuilder, context) {
        return sqlBuilder._appendColumnName(vs, context)
    },
    __toSqlForCondition(vs, sqlBuilder, context) {
        return sqlBuilder._appendColumnNameForCondition(vs, context)
    },
    __registerTableOrView(vs, sqlBuilder, requiredTablesOrViews) {
        __asTableOrViewRoot(vs.__tableOrView).__registerTableOrView(sqlBuilder, requiredTablesOrViews)
    },
    __registerRequiredColumn(vs, _sqlBuilder, requiredColumns, onlyForTablesOrViews) {
        if (onlyForTablesOrViews.has(vs.__tableOrView)) {
            requiredColumns.add(vs as any)
        }
    },
    __getOldValues(vs, sqlBuilder) {
        return __asTableOrViewRoot(vs.__tableOrView).__getOldValues(sqlBuilder)
    },
    __getValuesForInsert(vs, sqlBuilder) {
        return __asTableOrViewRoot(vs.__tableOrView).__getValuesForInsert(sqlBuilder)
    },
    __isAllowed(vs, sqlBuilder) {
        return __asTableOrViewRoot(vs.__tableOrView).__isAllowed(sqlBuilder)
    },
    // A column in the definition of a table, view or values can be marked: it must remain a column
    asRequiredInOptionalObject(vs) {
        const result = __copyOfValueSource(vs)
        result.__optionalType = 'requiredInOptionalObject'
        return result
    },
}

/** A column of a table, a view or values, of the data type of its class */
export function __newDBColumn(typeClass: DataTypeClass, table: AnyTableOrView, name: string): DBColumnValueSource {
    const vs = new (typeClass as unknown as ValueSourceConstructor)('required') as InCreation<DBColumnValueSource>
    vs.__node = dbColumnNode
    vs.__name = name
    vs.__tableOrView = table
    vs.__hasDefault = false
    vs.__isPrimaryKey = false
    vs.__isAutogeneratedPrimaryKey = false
    vs.__isComputed = false
    vs.__writable = false
    return vs
}

// The marks of a column of a table, a view or values (a value source with the node of a column): its table, view or
// values gives them while it creates the column, so they finish its creation
export function __asColumn(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    return column
}

export function __asOptionalColumn(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    column.__optionalType = 'optional'
    return column
}

export function __asOptional(column: InCreation<DBColumnValueSource>): any {
    // The optional column of a view: optional, but not writable. A view is read only, so its columns never receive a
    // value; the state of the column at run time matches its public type.
    column.__optionalType = 'optional'
    return column
}

export function __asColumnWithDefaultValue(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    column.__hasDefault = true
    return column
}

export function __asOptionalColumnWithDefaultValue(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    column.__optionalType = 'optional'
    column.__hasDefault = true
    return column
}

export function __asAutogeneratedPrimaryKey(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    column.__hasDefault = true
    column.__isPrimaryKey = true
    column.__isAutogeneratedPrimaryKey = true
    return column
}

export function __asAutogeneratedPrimaryKeyBySequence(column: InCreation<DBColumnValueSource>, sequenceName: string): any {
    column.__writable = true
    column.__hasDefault = true
    column.__isPrimaryKey = true
    column.__isAutogeneratedPrimaryKey = true
    column.__sequenceName = sequenceName
    return column
}

export function __asPrimaryKey(column: InCreation<DBColumnValueSource>): any {
    column.__writable = true
    column.__isPrimaryKey = true
    return column
}

export function __asComputedColumn(column: InCreation<DBColumnValueSource>): any {
    column.__isComputed = true
    return column
}

export function __asOptionalComputedColumn(column: InCreation<DBColumnValueSource>): any {
    column.__isComputed = true
    column.__optionalType = 'optional'
    return column
}
