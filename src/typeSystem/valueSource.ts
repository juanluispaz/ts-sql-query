export function isValueSource(value: any): value is AnyValueSource {
    if (value === undefined || value === null) {
        return false
    }
    if (typeof value === 'object') {
        return !!value[isValueSourceObject]
    }
    return false
}

export function __getValueSourceOfObject(obj: AnyTableOrView, prop: string): AnyValueSource | undefined {
    const result = (obj as any)[prop]
    if (!result) {
        return undefined
    }
    if (typeof result !== 'object') {
        return undefined
    }
    if (result[isValueSourceObject]) {
        return result as any
    } else {
        return undefined
    }
}

export function __getValueSourcePrivate(valueSource: AnyValueSource | HasSource<any>): __ValueSourcePrivate {
    return valueSource as any
}

