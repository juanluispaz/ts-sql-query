// Coverage of the optional `transformPlaceholder` hook of a user-defined
// TypeAdapter: the adapter rewrites the placeholder of each value bound for its
// column (here it wraps it in a cast) and delegates to `next` for the other
// types. The rows show the query still finds what it should with the rewritten
// placeholder.
//
// The cast is written by the adapter, so its SQL type is this database's: the
// two constants below are the only dialect-specific text of the file.

import { afterAll, beforeAll, beforeEach, describe, expect, test } from '../../../../lib/testRunner.js'
import { assertType, type Exact } from '../../../../lib/assertType.js'
import { CustomBooleanTypeAdapter, type DefaultTypeAdapter, type TypeAdapter, type TypeAdapterPlaceholderContext } from '../../../../../src/TypeAdapter.js'
import { Table } from '../../../../../src/Table.js'
import { DBConnection } from '../../domain/connection.js'
import { ctx } from './setup.js'

// The SQL types the adapters cast a placeholder to, in this database's syntax.
const STRING_CAST_TYPE = 'varchar2(64)'
const BOOLEAN_CAST_TYPE = 'number(1)'

function castPlaceholder(placeholder: string, sqlType: string): string {
    return 'cast(' + placeholder + ' as ' + sqlType + ')'
}

// A user adapter that casts the placeholder of a string and delegates to `next`
// for every other type.
const castString: TypeAdapter = {
    transformValueFromDB(value, context, next) { return next.transformValueFromDB(value, context) },
    transformValueToDB(value, context, next) { return next.transformValueToDB(value, context) },
    transformPlaceholder(placeholder, context, next) {
        if (context.requestedType === 'string') {
            return castPlaceholder(placeholder, STRING_CAST_TYPE)
        }
        return next.transformPlaceholder(placeholder, context)
    },
}

// The `project` table with `name` carrying the casting adapter.
const tProjectCastName = new class TProjectCastName extends Table<DBConnection, 'TProjectCastName'> {
    id   = this.column('id', 'int')
    name = this.column('name', 'string', castString)
    constructor() { super('project') }
}()

// A custom boolean stored as 'Y' / 'N' whose adapter also casts the placeholder
// of a boolean.
class CastingBooleanAdapter extends CustomBooleanTypeAdapter {
    constructor() { super('Y', 'N') }
    transformPlaceholder(placeholder: string, context: TypeAdapterPlaceholderContext, next: DefaultTypeAdapter): string {
        if (context.requestedType === 'boolean') {
            return castPlaceholder(placeholder, BOOLEAN_CAST_TYPE)
        }
        return next.transformPlaceholder(placeholder, context)
    }
}

// The `organization` table with `verified` ('Y' / 'N') as that custom boolean.
const tOrganizationCastVerified = new class TOrganizationCastVerified extends Table<DBConnection, 'TOrganizationCastVerified'> {
    id       = this.autogeneratedPrimaryKey('id', 'int')
    name     = this.column('name', 'string')
    verified = this.column('verified', 'boolean', new CastingBooleanAdapter())
    constructor() { super('"organization"') }
}()

describe(ctx.label, () => {
    beforeAll(() => ctx.up(), ctx.timeoutMs)
    afterAll(() => ctx.down(), ctx.timeoutMs)
    beforeEach(() => { ctx.reset() })

    test('transform-placeholder/a-column-adapter-rewrites-the-placeholder', async () => {
        // The value compared with `name` is bound with the adapter's cast around
        // its placeholder. Project 1 is 'Marketing site', and it is still found.
        ctx.mockNext([{ id: 1, name: 'Marketing site' }])
        const rows = await ctx.conn.selectFrom(tProjectCastName)
            .where(tProjectCastName.name.equals('Marketing site'))
            .select({ id: tProjectCastName.id, name: tProjectCastName.name })
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as "id", name as "name" from project where name = cast(:0 as varchar2(64))"`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            "Marketing site",
          ]
        `)
        assertType<Exact<typeof rows, Array<{ id: number; name: string }>>>()
        expect(rows).toEqual([{ id: 1, name: 'Marketing site' }])
    })

    test('transform-placeholder/forwarded-through-a-with', async () => {
        // The custom boolean is projected by a `with` and filtered outside it:
        // the outer column still uses the column's adapter for the placeholder,
        // so the value compared is bound with its cast. Organization 1
        // (verified 'Y') is the only verified one.
        const verifiedOrganizations = ctx.conn.selectFrom(tOrganizationCastVerified)
            .select({
                id:       tOrganizationCastVerified.id,
                name:     tOrganizationCastVerified.name,
                verified: tOrganizationCastVerified.verified,
            })
            .forUseInQueryAs('verifiedOrganizations')

        ctx.mockNext([{ id: 1, name: 'Acme Corp' }])
        const rows = await ctx.conn.selectFrom(verifiedOrganizations)
            .where(verifiedOrganizations.verified.equals(true))
            .select({ id: verifiedOrganizations.id, name: verifiedOrganizations.name })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"with verifiedOrganizations as (select id as id, name as name, case when verified = 'Y' then 1 else 0 end as verified from "organization") select id as "id", name as "name" from verifiedOrganizations where verified = cast(:0 as number(1)) order by "id""`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`
          [
            1,
          ]
        `)
        assertType<Exact<typeof rows, Array<{ id: number; name: string }>>>()
        expect(rows).toEqual([{ id: 1, name: 'Acme Corp' }])
    })

    test('transform-placeholder/a-rendered-null-goes-through-the-adapter', async () => {
        // `name.onlyWhenOrNull(false)` is the null of the `name` column, which
        // carries the adapter: that null is written through the adapter too, so
        // the adapter's cast appears around it in the select list. It comes back
        // null for every project (ids 1 to 4), so the optional `n` is absent.
        ctx.mockNext([{ id: 1, n: null }, { id: 2, n: null }, { id: 3, n: null }, { id: 4, n: null }])
        const rows = await ctx.conn.selectFrom(tProjectCastName)
            .select({ id: tProjectCastName.id, n: tProjectCastName.name.onlyWhenOrNull(false) })
            .orderBy('id')
            .executeSelectMany()
        expect(ctx.lastSql).toMatchInlineSnapshot(`"select id as "id", cast(null as varchar2(64)) as "n" from project order by "id""`)
        expect(ctx.lastParams).toMatchInlineSnapshot(`[]`)
        assertType<Exact<typeof rows, Array<{ id: number; n?: string }>>>()
        expect(rows).toEqual([{ id: 1 }, { id: 2 }, { id: 3 }, { id: 4 }])
    })
})
